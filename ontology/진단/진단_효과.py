"""효과 시험(메모리 안에서 규범을 빼 게이트만 다시 돌린다. DB 를 바꾸지 않는다)."""
import sys, os, json, collections
sys.stdout.reconfigure(encoding='utf-8')
R = os.environ['REPO']
sys.path[:0] = [R, R + '/scripts']
os.environ['SUDDOE_ONTOLOGY_PROGRAMS'] = '모두의 창업 프로젝트'
from _lib import db
import ontology_lookup as L, ontology_gate as G, orchestrate as O
사업 = '모두의 창업 프로젝트'


def 돌리기(cur, 비목, 세목, 금액, 부가세, 추가=None, 품목=None, 뺄=None):
    대상 = L.대상_노드(cur, 사업, 비목, 세목)
    품목id = L.품목_노드(cur, 사업, 품목, 대상['대상_id'])
    시작 = 품목id or 대상['대상_id']
    적용 = L.적용_규범(cur, 사업, 시작)
    규범 = [n for n in 적용['규범'] if not (뺄 and 뺄(n))]
    return G.게이트(규범, O.게이트_입력(금액, 부가세, 추가), 확정=True, 세목표시=세목, 우선순위_적용=적용['우선순위_적용'],
                 세목미정=False), 시작


with db.connect(autocommit=True) as c:
    cur = c.cursor()
    print('--- 게이트 순서: 앞 한도 갈림이 뒤 한도의 확정 초과를 가리는가')
    g, _ = 돌리기(cur, '지급수수료', '멘토링비', 320000, '포함', {'인원': 1, '일수': 1, '시간': 1})
    print('멘토링 32만 · 1인1일 · 1시간(시간당 한도 10만의 3배):', g['종류'], g['검증코드'], g['코드판정'])
    g2, _ = 돌리기(cur, '지급수수료', '멘토링비', 320000, '포함', {'인원': 1, '일수': 1, '시간': 1}, 뺄=lambda n: n['norm_id'] == '규범:모두의창업/제36조①/한도/1')
    print(' 1일 한도 규범을 빼면:', g2['종류'], g2['코드판정'])
    print('--- 표-10 정의없음 임계값을 빼면 2천만 경계')
    for 금액, 부 in ((20000000, '포함'), (20000001, '포함'), (21000000, '포함'), (19000000, '공급가액')):
        a, _ = 돌리기(cur, '외주용역비', None, 금액, 부)
        b, _ = 돌리기(cur, '외주용역비', None, 금액, 부, 뺄=lambda n: n['norm_id'] == '규범:공통/지침#제36조①표-10/임계값/1')
        c2, _ = 돌리기(cur, '재료비', None, 금액, 부)
        d2, _ = 돌리기(cur, '재료비', None, 금액, 부, 뺄=lambda n: n['norm_id'] == '규범:공통/지침#제36조①표-10/임계값/1')
        print(f'외주 {금액:,} {부}: {a["종류"]} → {b["종류"]} (조건 {len(b["조건"])}) | 재료비: {c2["종류"]} → {d2["종류"]}')
    print('--- 상한 원인: 구분별로 빼 보면 몇 라벨에서 상한이 사라지나 (100만원 · 포함)')
    lab = [x for x in L.레이블_목록(cur, 사업) if x['비목'] in ('재료비', '외주용역비', '기계장치', '지급수수료', '여비', '특허권등무형자산취득비', '창업활동비')]
    세기 = collections.Counter()
    for x in lab:
        g, _ = 돌리기(cur, x['비목'], x['세목'], 1000000, '포함')
        if g['종류']:
            continue
        세기['라벨'] += 1
        구분 = {c_['구분'] for c_ in g['조건']}
        세기['의무 있음'] += '의무' in 구분
        세기['금지조건 있음'] += '금지조건' in 구분
        세기['미확정규범 있음'] += '미확정규범' in 구분
        세기['입력비움 있음'] += '입력비움' in 구분
        세기['의무 말고 다른 구분 없음'] += 구분 <= {'의무'}
        세기['의무+금지조건 말고 없음'] += 구분 <= {'의무', '금지조건'}
    print(dict(세기))
    print('--- 자연어 조건 의무: 해당 없는 지출에 뜨는 줄 수 (재료비 100만)')
    g, _ = 돌리기(cur, '재료비', None, 1000000, '포함')
    표 = {G._규범문장(n): n for n in L.적용_규범(cur, 사업, '비목:창업/재료비')['규범']}
    for c_ in g['조건']:
        n = 표.get(c_['문장'])
        if n and G._자연어조건(n):
            print('  ', c_['구분'], c_['문장'][:70], '|| 조건:', G._자연어조건(n)[:50])
