def 납작(s: str) -> str:
    """표가 눌려 줄로 쪼개진 원문 대응 — 공백을 전부 지운다."""
    return re.sub(r"\s+", "", s or "")


def 본문찾기(cur, doc_id: str, 조번호: str) -> str | None:
    """🔴 `status` 는 `doc_articles` 가 아니라 `documents` 에 있다. 조인해야 한다.
    (`삭제` 플래그는 조 단위라 `doc_articles` 쪽이다 — 둘 다 걸어야 현행 조만 남는다.
     어휘검산.py:58-60 과 같은 잣대를 쓴다 — 검사기끼리 기준이 갈리면 안 된다)"""
    cur.execute("select a.본문 from corpus.doc_articles a join corpus.documents d using(doc_id) "
                "where d.status='active' and d.doc_id=%s and a.조번호=%s and not a.삭제",
                (doc_id, 조번호))
    r = cur.fetchone()
    return r[0] if r else None


def DB_스칼라값(cur, rule_id) -> dict:
    """corpus.rules 의 스칼라 칸 3개(한도)를 rule_id 로 한 번에 뽑는다.

    🔴 `사전승인_조건` 은 여기 없다 — TEXT[] 로 바뀌어 더 이상 스칼라가 아니다
    (아래 `DB_배열값()` 참조).
    """
    cur.execute('SELECT "한도_유형","한도_값","한도_단위" '
                'FROM corpus.rules WHERE rule_id=%s', (rule_id,))
    r = cur.fetchone()
    if not r:
        return {}
    return dict(zip(("한도_유형", "한도_값", "한도_단위"), r))


def DB_배열값(cur, rule_id) -> dict:
    """corpus.rules 의 array 칸 3개(금지예시·허용예시·사전승인_조건)를 뽑는다."""
    cur.execute('SELECT "금지예시","허용예시","사전승인_조건" '
                'FROM corpus.rules WHERE rule_id=%s', (rule_id,))
