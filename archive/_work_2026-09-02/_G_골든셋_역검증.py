def main() -> int:
    l1 = {it["비목"]: it for it in SR.지침공통}

    # 🔴 autocommit — 8세션 병렬 중 읽기 트랜잭션을 붙들면 남의 DDL 과 교착난다.
    #    2026-09-01 실측: B 의 idle-in-transaction 886초가 D 의 04_agent.sql 을 막고,
    #    그 DDL 이 corpus.rules 에 AccessExclusiveLock 을 쥔 채 대기해 **아무도 rules 를
    #    읽지 못하는** 상태가 됐다. 조회용 커넥션은 트랜잭션을 열지 않는다.
    with psycopg.connect(DSN, autocommit=True) as conn:
        golden = conn.execute(
            "SELECT gold_id, 정답판정, 질문 FROM eval.golden_set "
            "WHERE 적용범위 IS NOT NULL ORDER BY gold_id").fetchall()

    print(f"== 공통 문항 {len(golden)}건 (적용범위 IS NOT NULL · 사업명 NULL)\n")

    치명 = []
    과잉 = []
    미커버 = []

    for gid, 정답, 질문 in golden:
        비목, 근거 = 배정.get(gid, (None, "배정 없음"))
        룰 = l1.get(비목) if 비목 else None
        허용 = 룰["허용"] if 룰 else "—(룰 없음)"

        if 룰 is None:
            mark = "⚪ 미커버"
            미커버.append((gid, 정답, 질문, 근거))
        elif 허용 == "가능" and 정답 in ("불가", "조건부"):
            mark = "🔴 치명"
            치명.append((gid, 정답, 허용, 질문))
        elif 정답 == "가능" and 허용 != "가능":
            mark = "⚠️ 안전측과잉"
            과잉.append((gid, 정답, 허용, 질문))
        else:
            mark = "✅"

        print(f"{mark:<8} {gid:>3} 정답={정답:<4} 룰={허용:<5} {str(비목 or '-'):<12} {질문[:44]}")
        print(f"{'':>12} 근거: {근거}")

    print()
    print(f"== 🔴 치명(정답이 불가/조건부인데 룰이 가능): {len(치명)}  ← 0 이어야 한다")
    for r in 치명:
        print("   ", r)
    print(f"== ⚠️ 안전측 과잉(정답 가능인데 룰이 더 엄격): {len(과잉)}  ← 치명 아님, 기록만")
    for gid, 정답, 허용, 질문 in 과잉:
        print(f"    {gid} 정답={정답} 룰={허용} {질문[:60]}")
    print(f"== ⚪ L1 공통행이 못 덮는 문항: {len(미커버)}  ← 룰 없음 = 판단불가(안전)")
    for gid, 정답, 질문, 근거 in 미커버:
        print(f"    {gid} 정답={정답} {질문[:52]}")
        print(f"        {근거}")

    # 정답 '불가' 문항이 실제로 금지예시에 걸리는지 — 금지목록 즉답(B1)의 재료 점검
    print("\n== 정답 '불가' 문항의 금지예시 보유 여부 (B1 즉답 경로 재료)")
    for gid, 정답, 질문 in golden:
        if 정답 != "불가":
            continue
        비목, _ = 배정.get(gid, (None, ""))
        룰 = l1.get(비목) if 비목 else None
        n = len(룰["금지예시"]) if 룰 else 0
        상태 = "✅" if n else "⚪"
        print(f"   {상태} {gid:>3} {str(비목 or '-'):<12} 금지예시 {n:>2}건  {질문[:40]}")

    return 1 if 치명 else 0


if __name__ == "__main__":
    sys.exit(main())
