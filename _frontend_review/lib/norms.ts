"use client";

/**
 * 「이 사업에 어떤 규정이 적용되는가」 — 마이페이지 '공통 관리 기준' 표기용.
 *
 * ══════════════════════════════════════════════════════════════════════
 * 주의: 2026-09-07 — `GET /api/programs` 가 `우선순위규칙목록` 을 포함해 보내기
 *    시작했습니다(`corpus.precedence_rules`, `verified=true` 행만, 서버 커밋
 *    `7fcd665`). 그전에는 이 정보를 주는 API 가 없어서(2026-09-07 조사)
 *    8사업 표를 프론트에 하드코딩해 뒀는데, 이제 서버 응답만 옮깁니다 —
 *    프론트가 지어내는 문구는 없습니다.
 *
 * 주의: `해석` 컬럼이 이미 사람이 쓴 한 문장입니다(예: "주관기관 규정이 더 엄격해도
 *    세부관리기준이 우선 적용된다"). 프론트가 다시 요약하지 않고 그대로 씁니다.
 *
 * 주의: 나중에 이 API 가 없어지거나 모양이 바뀌면 `기본규정()` 하나만 남습니다 —
 *    화면은 `use적용규정(사업명)` 한 훅만 부릅니다(`app/checkumait-app.tsx`).
 * ══════════════════════════════════════════════════════════════════════
 */

import { 사업목록 } from "./api";
import { API켜짐 } from "./config";
import type { 우선순위규칙 } from "./server-types";

export type 적용규정항목 = {
  제목: string;
  설명: string;
};

/** "2026 초격차 스타트업 1000+" → "초격차스타트업1000+" — 서버 사업명과 비교용. */
function 비교키(s: string): string {
  return (s ?? "").replace(/^\s*20\d\d\s*/, "").replace(/[\s·・+()]/g, "").toLowerCase();
}

/**
 * 서버를 못 부르거나 이 사업 행이 아직 없을 때 씁니다.
 * 주의: 표에 없는 사업이면 지어내지 않고 '사업명 + 세부관리기준' 까지만 말합니다.
 */
export function 기본규정(사업명: string): 적용규정항목[] {
  return [
    {
      제목: `${(사업명 ?? "").replace(/^\s*20\d\d\s*/, "").trim()} 세부관리기준`,
      설명: "중소벤처기업부·창업진흥원 · 이 사업의 집행 기준",
    },
  ];
}

/**
 * `precedence_rules` 한 행 → 화면 한 줄.
 *
 * 주의: `우선규범` 이 비어 있는 행(예: "이 사업의 세부관리기준이 L3 주관기관 규정보다
 *    우선한다")은 그 사업 자신의 세부관리기준을 말하는 것이라 제목을 그렇게 채웁니다.
 *    `우선규범` 이 채워진 행(예: "운영요령·통합관리지침이 이 사업의 세부관리기준보다
 *    우선한다")은 그 상위 문서 이름을 그대로 제목에 씁니다.
 */
function 규칙을항목으로(r: 우선순위규칙, 사업명: string): 적용규정항목 {
  return {
    제목: (r.우선규범 && r.우선규범.trim()) || `${사업명} 세부관리기준`,
    설명: (r.해석 && r.해석.trim()) || (r.우선규범 as string) || "",
  };
}

/**
 * 이 사업에 적용되는 규정 목록을 서버에서 읽습니다.
 * 실패하거나 이 사업 행이 없으면(또는 규칙이 0건이면) `null` — 호출부는 `기본규정()` 을 씁니다.
 */
export async function 서버규정읽기(사업명: string): Promise<적용규정항목[] | null> {
  if (!API켜짐()) return null;
  try {
    const r = await 사업목록();
    const 목록 = r?.사업 ?? [];
    const 키 = 비교키(사업명);
    const 찾음 =
      목록.find((p) => 비교키(p.사업명) === 키) ??
      목록.find((p) => (p.별칭 ?? []).some((a) => 비교키(a) === 키));
    const 규칙들 = 찾음?.우선순위규칙목록 ?? [];
    if (!규칙들.length) return null;
    return 규칙들.map((r) => 규칙을항목으로(r, 찾음!.사업명));
  } catch {
    return null;
  }
}
