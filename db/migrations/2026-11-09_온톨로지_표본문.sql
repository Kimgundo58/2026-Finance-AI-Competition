DECLARE r record; actual text; old_count integer := 0; new_count integer := 0; changed integer; cache_deleted integer := 0;
BEGIN
  FOR r IN SELECT * FROM suddoe_table_body_20261109 ORDER BY doc_id, 조번호 LOOP
    IF encode(sha256(convert_to(r.new_body, 'UTF8')), 'hex') <> r.new_sha256 THEN
      RAISE EXCEPTION '새 본문 SHA-256 불일치: % / %', r.doc_id, r.조번호;
    END IF;
    SELECT encode(sha256(convert_to(a.본문, 'UTF8')), 'hex') INTO actual
      FROM corpus.doc_articles a JOIN corpus.documents d ON d.doc_id=a.doc_id
      WHERE a.doc_id=r.doc_id AND a.조번호=r.조번호 AND d.status='active' FOR UPDATE OF a, d;
    IF NOT FOUND THEN RAISE EXCEPTION 'active 대상 조문이 없다: % / %', r.doc_id, r.조번호; END IF;
    IF actual = r.old_sha256 THEN old_count := old_count + 1;
    ELSIF actual = r.new_sha256 THEN new_count := new_count + 1;
    ELSE RAISE EXCEPTION '기존 본문 SHA-256 불일치: % / %', r.doc_id, r.조번호;
    END IF;
  END LOOP;
  IF old_count + new_count <> 5 OR (old_count <> 0 AND new_count <> 0) THEN
    RAISE EXCEPTION '대상 다섯 조문이 기존/신규 혼합 상태다';
  END IF;
  UPDATE corpus.doc_articles a SET 본문 = s.new_body
    FROM suddoe_table_body_20261109 s
    WHERE a.doc_id=s.doc_id AND a.조번호=s.조번호
      AND encode(sha256(convert_to(a.본문, 'UTF8')), 'hex')=s.old_sha256;
  GET DIAGNOSTICS changed = ROW_COUNT;
  IF changed <> old_count THEN RAISE EXCEPTION '갱신 수 불일치: % / %', changed, old_count; END IF;
  IF changed > 0 THEN
