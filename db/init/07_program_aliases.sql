-- 07_program_aliases.sql — 프론트 표기를 별칭으로 흡수 (2026-09-02)
--
-- 🔴 이 셋은 「표기 흔들림」이 아니라 **이름 자체가 다른 것**이다.
--    접두사·공백·가운뎃점 정규화(server/main.py 진입점)로는 안 붙는다.
--    정규화로 억지로 맞추면 「초격차 스타트업 1000+」가 「초격차 스타트업 프로젝트」가
--    되는 규칙을 만들어야 하는데, 그건 정규화가 아니라 번역이다.
--
-- 🔴 정본은 안 바꾼다. `corpus.chunks.사업명` 8종이 정본이고 조인 키로 널리 쓰인다
--    (2026-09-02 전수조사: 다운스트림 250여 곳이 `WHERE 사업명 = %s`).
--    별칭은 덧붙이는 것이라 정본 결정을 막지 않는다.
--
-- 모두의창업: 프론트 「일반・기술」이 트랙 범위를 더 정확히 밝히는 표기인 건 맞다.
--    다만 그 구분은 `corpus.programs.트랙범위` 가 이미 문장으로 갖고 있고,
--    사업명까지 트랙을 지고 가면 조인 키 250여 곳이 흔들린다. 별칭으로 흡수한다.
--    ⚠️ 가운뎃점이 U+30FB(KATAKANA MIDDLE DOT)다. TIPS 쪽은 U+00B7 로 서로 다르다.
--       NFC/NFD/NFKC/NFKD 어느 정규화로도 둘은 안 합쳐진다 (2026-09-02 실측).
--       그래서 **원문 코드포인트 그대로** 넣는다.
-- ════════════════════════════════════════════════════════════════

UPDATE corpus.programs SET "별칭" = "별칭" || ARRAY['모두의 창업 일반・기술']
 WHERE "사업명" = '모두의 창업 프로젝트'
   AND NOT ('모두의 창업 일반・기술' = ANY("별칭"));

UPDATE corpus.programs SET "별칭" = "별칭" || ARRAY['초격차 스타트업 1000+']
 WHERE "사업명" = '초격차 스타트업 프로젝트'
   AND NOT ('초격차 스타트업 1000+' = ANY("별칭"));

UPDATE corpus.programs SET "별칭" = "별칭" || ARRAY['민관공동 창업자 발굴·육성']
 WHERE "사업명" = 'TIPS'
   AND NOT ('민관공동 창업자 발굴·육성' = ANY("별칭"));
