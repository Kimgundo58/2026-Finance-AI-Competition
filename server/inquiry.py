# -*- coding: utf-8 -*-
"""판정이 「확인 필요」 이고 근거가 부족할 때 사용자가 주관기관에 보낼 문의 초안을 만든다.

판정은 가능 · 확인 필요 · 불가 3종이다(2026-11-11 사용자 결정). 옛 판단불가(판정 실패 · 쓸 근거 없음)였던 경우에만
초안을 만들고, 조건 · 한도 · 증빙만 확인하면 되는 확인 필요(옛 조건부)에는 만들지 않는다. 가르는 기준은 `근거부족()` 이다.
판정 응답(judge_response·routes_judge)과 routes_plans 의 계획 상세 조회가 `문의초안()` 을 호출한다.
LLM 을 부르지 않고, 계획에 이미 있는 값(사업명·용도·비목·품목·금액)으로 코드가 템플릿으로 문장을 작성한다.
없는 값은 지어내지 않고 해당 줄을 빼며, 품목과 금액이 모두 없으면 None 을 반환한다.

형식(v030, 2026-11-11 팀 결정):
    제목 : [[팀명]] 창업지원자금 집행 관련 문의

    안녕하세요.
    {사업명} [팀명]입니다.
    {용도}을 위해 아래 항목을 {비목}으로 집행이 가능한지 문의드립니다.

    - 지출 항목 : {품목}
    - 예상 금액 : 약 {금액}

    확인 부탁드립니다. 감사합니다.

`[팀명]` 은 자리표시자로 그대로 둔다. 팀 이름의 기준 데이터는 Supabase 계정 정보라 서버가 확실히 알 수 없다.
화면이 계정의 팀 이름으로 바꿔 보여 주고, 모르면 사용자가 직접 채운다.
참고 링크 줄은 계획에 링크 값이 없어 넣지 않는다.
"""
from __future__ import annotations

import re

팀명 = "[팀명]"
맺음말 = "확인 부탁드립니다. 감사합니다."

# 근거부족: 판정이 확인 필요인데 판정 자체를 하지 못했거나(실패) 쓸 근거가 없었던 경우. 옛 4값의 판단불가 자리다.
# 검증코드: 판정값 enum 밖(INVALID_JUDGMENT) · 인용 0건(NO_CITATION) · 부가세 기준 미정 코드 판정(VAT_BASIS_UNKNOWN).
_근거부족_검증코드 = frozenset({"INVALID_JUDGMENT", "NO_CITATION", "VAT_BASIS_UNKNOWN"})
# 처리단계: 검수 전 한도를 입력 금액이 넘음(orchestrate._새_검증단계) · 요약 금액이 맞지 않음(실패로 둔다) ·
# 판정 LLM 이 근거를 인용했지만 주관기관 해석 · 승인이 있어야 결론이 난다고 봄(orchestrate._확인대상_반영)
_근거부족_처리단계 = frozenset({"미확정한도초과", "요약금액불일치", "주관기관확인"})


def 근거부족(결과: dict | None) -> bool:
    """판정 결과(orchestrate.판정 출력 또는 tenant.decisions 행)가 문의 초안 대상인지.

    판정이 「확인 필요」 이고 다음 중 하나면 True: 실패 경로(실패경로 · 실패단계) · 인용 0건 ·
    `_근거부족_검증코드` · `_근거부족_처리단계`. LLM 이 근거를 인용하며 낸 확인 필요는 여기 들지 않는다.
    """
    if not 결과 or 결과.get("판정") != "확인 필요":
        return False
    if 결과.get("실패경로") or 결과.get("실패단계"):
        return True
    인용 = 결과["인용목록"] if "인용목록" in 결과 else 결과.get("인용")
    if not 인용:
        return True
    if _근거부족_검증코드 & set(결과.get("검증코드") or ()):
        return True
    단계 = 결과.get("처리단계") or ""
    단계들 = set(단계.split("+")) if isinstance(단계, str) else set(단계)
    return bool(_근거부족_처리단계 & 단계들)


def 금액표기(금액) -> str | None:
    """`2500000` → `250만원`. 만 단위로 나누어떨어지지 않으면 `2,500,000원`.

    값이 없거나 0 이하면 None 이다(0원이 아니라 금액을 모른다는 뜻).
    """
    if 금액 is None or isinstance(금액, bool):
        return None
    try:
        n = int(round(float(금액)))
    except (TypeError, ValueError):
        return None
    if n <= 0:
        return None
    if n % 10000 == 0:
        만 = n // 10000
        if 만 % 10000 == 0:                       # 억 단위로 나누어떨어질 때만 억으로 표기한다
            return f"{만 // 10000}억원"
        return f"{만:,}만원"
    return f"{n:,}원"


def _받침(단어: str) -> int | None:
    """마지막 글자의 받침 번호(0 = 없음). 한글이 아니면 None."""
    끝 = 단어.rstrip()[-1:] or " "
    if "가" <= 끝 <= "힣":
        return (ord(끝) - 0xAC00) % 28
    return None


def _을를(단어: str) -> str:
    b = _받침(단어)
    return 단어 + ("를" if b == 0 else "을" if b else "(을)를")


def _으로(단어: str) -> str:
    b = _받침(단어)
    return 단어 + ("로" if b in (0, 8) else "으로" if b else "(으)로")   # 8 = ㄹ 받침


def 문의초안(정규화: dict, 결과: dict | None, 사업명: str | None,
           비목: str | None = None) -> str | None:
    """근거부족(결과) 인 판정을 주관기관에 보낼 문의 문장으로 만든다. 아니거나 품목·금액이 모두 없으면 None."""
    if not 근거부족(결과):
        return None

    정규화 = 정규화 or {}
    품목 = str(정규화.get("품목") or "").strip()
    금액문 = 금액표기(정규화.get("금액"))
    if not 품목 and not 금액문:
        return None

    사업 = str(사업명 or 정규화.get("사업명") or "").strip()
    용도 = str(정규화.get("용도") or "").strip()
    # 끝 괄호 덧말은 뺀다: 「QA진행 (QA진행하면서 회의 진행할 예정)」 → 「QA진행을 위해」(괄호로 끝나면 조사가 「(을)를」 이 된다)
    용도 = re.sub(r"\s*\([^()]*\)$", "", 용도).strip() or 용도
    비목 = str(비목 or "").strip()

    소개 = f"{사업} {팀명}입니다." if 사업 else f"{팀명}입니다."
    앞 = f"{_을를(용도)} 위해 " if 용도 else ""
    어디로 = _으로(비목) if 비목 else "사업비로"
    문의 = f"{앞}아래 항목을 {어디로} 집행이 가능한지 문의드립니다."

    항목 = [f"- 지출 항목 : {품목}"] if 품목 else []
    if 금액문:
        항목.append(f"- 예상 금액 : 약 {금액문}")

    return "\n\n".join([
        f"제목 : [{팀명}] 창업지원자금 집행 관련 문의",
        f"안녕하세요.\n{소개}\n{문의}",
        "\n".join(항목),
        맺음말,
    ])


if __name__ == "__main__":
    s = 문의초안({"품목": "MVP 앱 외주 개발", "금액": 12000000, "용도": "서비스 시제품 앱 개발"},
             {"판정": "확인 필요", "인용": []}, "모두의 창업", "외주용역비")
    print(s)
    assert "모두의 창업 [팀명]입니다." in s
    assert "서비스 시제품 앱 개발을 위해 아래 항목을 외주용역비로 집행이" in s
    assert "- 예상 금액 : 약 1,200만원" in s and "None" not in s
    assert _으로("지급수수료") == "지급수수료로" and _으로("재료비") == "재료비로" and _으로("인건비") == "인건비로"
    assert _으로("시제품 제작비") == "시제품 제작비로" and _으로("기계장치") == "기계장치로" and _으로("임차료") == "임차료로"
    assert _으로("교육훈련") == "교육훈련으로" and _을를("홍보") == "홍보를" and _을를("앱 개발") == "앱 개발을"
    부족 = {"판정": "확인 필요", "실패경로": True}
    assert 문의초안({"품목": "노트북"}, 부족, None) .startswith("제목 : [[팀명]]")
    assert 문의초안({}, 부족, "모두의 창업") is None
    assert all(문의초안({"품목": "노트북", "금액": 1}, {"판정": p, "인용": []}, "x") is None for p in ("가능", "불가"))
    # 근거를 인용한 확인 필요(옛 조건부)에는 만들지 않는다
    assert 문의초안({"품목": "노트북", "금액": 1}, {"판정": "확인 필요", "인용목록": [{"문장ID": "S01"}]}, "x") is None
    assert 근거부족({"판정": "확인 필요", "인용": [{}], "검증코드": ["VAT_BASIS_UNKNOWN"]})
    assert 근거부족({"판정": "확인 필요", "인용": [{}], "처리단계": "온톨로지+미확정한도초과+검증"})
    assert not 근거부족({"판정": "확인 필요", "인용": [{}], "검증코드": ["UNVERIFIED_RULE"], "처리단계": "코드상한"})
    # 근거를 인용했지만 주관기관 해석 · 승인이 있어야 결론이 나는 확인 필요(판정 LLM 의 확인대상)
    assert 근거부족({"판정": "확인 필요", "인용": [{}], "처리단계": "온톨로지+판정생성+주관기관확인+검증"})
    # 용도가 괄호 덧말로 끝나도 조사가 맞는다(2026-11-12 디버그 실행에서 「…예정)(을)를 위해」)
    괄호 = 문의초안({"품목": "회의실 1일 대여", "금액": 80000, "용도": "QA진행 (QA진행하면서 회의 진행할 예정)"},
               {"판정": "확인 필요", "인용": [{}], "처리단계": "주관기관확인"}, "모두의 창업", "창업활동비")
    assert "QA진행을 위해 아래 항목을 창업활동비로" in 괄호, 괄호
    assert "(을)를" not in 괄호
    print("OK")
