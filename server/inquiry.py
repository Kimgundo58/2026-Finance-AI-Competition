# -*- coding: utf-8 -*-
"""판단불가일 때 사용자가 주관기관에 보낼 «문의 초안» 을 만든다.   **[판정 계통]**

🔴 **LLM 을 부르지 않는다.** CLAUDE.md 확정 원칙이 「판정 1건 = LLM 2회(① 정규화
   ④ 조립)」다. 여기서 3회째를 만들면 호출 수 고정·지연 예측·재현성이 전부 깨진다.
   **판정이 이미 손에 쥔 값으로 코드가 문장을 조립한다.** 그게 이 모듈의 전부다.

🔴 **없는 값을 지어내지 않는다.** 필드가 없으면 그 «문장을 통째로 뺀다» —
   「미상」·「-」·빈 괄호·「제0조」 같은 흔적을 남기지 않는다. 초안 하나에 그런 자국이
   한 개만 있어도 문서 전체가 「AI 가 지어냈다」로 읽히고, 그러면 이 기능은 마이너스다.
   남길 게 아무것도 없으면 **`None`** 을 돌려준다 — 인사말만 남은 초안은 없느니만 못하다.

🔴 **규정 «원문» 을 옮기지 않는다.** 조번호·조제목까지다(계약 밖).

■ 본문의 축은 `인용` 이 아니라 `전제` 다
  판단불가는 대개 **근거를 못 찾아서** 판단불가다 — 그래서 `인용` 이 비어 있는 경우가
  흔하다. 「무엇이 확인이 안 돼서 못 정했는가」가 문의의 내용이고, 그건 `전제` 에 있다.

■ 전제를 «목록» 으로 쓰는 이유 (중앙 지시와 다른 부분 — 의도적이다)
  지시는 `사실` 을 「~인지 확인이 필요합니다」로 이으라는 것이었다. 그런데 실제 `사실` 은
  이미 «다» 로 끝나는 완결문이다 — 실측: `협약 총액이 확인되지 않았다` ·
  `해당 품목의 비목이 확정되지 않았다`. 그대로 이으면
  「협약 총액이 확인되지 않았**는지 확인이 필요합니다**」가 되어 **뜻이 뒤집힌다.**
  `사실` 을 손대 어미를 고치는 건 곧 «문장을 지어내는» 것이라 더 나쁘다.
  → `사실` 을 **한 글자도 안 바꾸고** 목록으로 싣고, 이끄는 문장만 코드가 붙인다.
"""
from __future__ import annotations

import re

# doc_id 앞의 레이어 접두사와 뒤의 날짜 토큰만 떼어 «읽을 수 있는 규범명» 으로 만든다.
# 🔴 여기까지가 기계적 변환이다. 이 이상 이름을 «해석» 하면 지어내는 것이 된다.
_레이어접두 = re.compile(r"^L[1-4]_")
_뒤날짜 = re.compile(r"[_\s]\d{8}$")

인사 = "안녕하세요."
맺음 = "확인 부탁드립니다. 감사합니다."


def _규범명(doc_id) -> str:
    """`L1_중소기업창업_지원사업_통합관리지침_제14차개정_20251223`
       → `중소기업창업 지원사업 통합관리지침 제14차개정`"""
    s = str(doc_id or "").strip()
    if not s:
        return ""
    s = _레이어접두.sub("", s)
    s = _뒤날짜.sub("", s)
    return s.replace("_", " ").strip()


def 금액표기(금액) -> str | None:
    """`2500000` → `250만원` · 만 단위로 안 떨어지면 `2,500,000원` · 없으면 `None`.

    🔴 `None` 은 「0원」이 아니라 「모른다」다. 부르는 쪽이 괄호째 빼야 한다.
    """
    if 금액 is None or isinstance(금액, bool):
        return None
    try:
        n = int(round(float(금액)))
    except (TypeError, ValueError):
        return None
    if n <= 0:
        return None
    if n % 10000 == 0:
        만 = n // 10000
        if 만 % 10000 == 0:                       # 1억 단위까지만 접는다
            return f"{만 // 10000}억원"
        return f"{만:,}만원"
    return f"{n:,}원"


def _인용문장(인용: list) -> str | None:
    """「{규범명} {조번호}({조제목}) 기준을 확인했습니다.」 — 최대 2건.

    🔴 조번호가 없으면 그 인용을 **통째로 건너뛴다.** 「제0조」·빈 괄호를 만들지 않는다.
    """
    조각 = []
    for c in 인용 or []:
        if not isinstance(c, dict):
            continue
        조번호 = str(c.get("조번호") or "").strip()
        if not 조번호:
            continue
        제목 = str(c.get("조제목") or "").strip()
        규범 = _규범명(c.get("doc_id"))
        한건 = " ".join(x for x in (규범, 조번호) if x)
        if 제목:
            한건 += f"({제목})"
        조각.append(한건)
        if len(조각) == 2:
            break
    if not 조각:
        return None
    return f"{' · '.join(조각)} 기준을 확인했습니다."


def _전제블록(전제: list) -> list[str]:
    """확인이 필요한 것. 🔴 `사실` 은 한 글자도 안 바꾼다 (모듈 docstring 참조)."""
    사실들 = []
    for t in 전제 or []:
        사실 = (t.get("사실") if isinstance(t, dict) else t)
        사실 = str(사실 or "").strip()
        if 사실 and 사실 not in 사실들:
            사실들.append(사실)
    if not 사실들:
        return []
    return ["아래 사항이 확인되지 않아 자체적으로 판단하기 어렵습니다."] + [
        f"- {x}" for x in 사실들]


def 문의초안(정규화: dict, 판정: str, 인용: list, 전제: list,
           사업명: str | None) -> str | None:
    """판단불가 판정을 «주관기관에 보낼 문의» 로 옮긴다. 아니면 `None`.

    🔴 `판정 != "판단불가"` 면 아무것도 안 만든다. 부르는 쪽(`main.py`)이 falsy 면
       키를 아예 안 싣는 모양이라, 여기서 `None` 을 주는 것이 「안 싣는다」와 같다.
    """
    if 판정 != "판단불가":
        return None

    정규화 = 정규화 or {}
    사업 = str(사업명 or 정규화.get("사업명") or "").strip()
    머리 = f"{인사} {사업} 참여기업입니다." if 사업 else 인사

    품목 = str(정규화.get("품목") or "").strip()
    돈 = 금액표기(정규화.get("금액"))
    본문: list[str] = []
    if 품목:
        # 🔴 금액을 모르면 괄호째 뺀다. `()` 나 `(미상)` 을 남기지 않는다.
        대상 = f"{품목}({돈})" if 돈 else 품목
        본문.append(f"{대상} 집행이 사업비로 가능한지 문의드립니다.")
    elif 돈:
        본문.append(f"{돈} 집행이 사업비로 가능한지 문의드립니다.")

    근거 = _인용문장(인용)
    if 근거:
        본문.append(근거)
    본문 += _전제블록(전제)

    # 🔴 인사말·맺음말만 남은 초안은 «없느니만 못하다». 본문이 비면 안 만든다.
    if not 본문:
        return None
    return "\n\n".join([머리, "\n".join(본문), 맺음])
