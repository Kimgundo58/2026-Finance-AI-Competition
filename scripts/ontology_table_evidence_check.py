# -*- coding: utf-8 -*-
"""앞쪽 표의 원문 좌표와 모호한 입력의 실패를 검사한다."""
from ontology_table_evidence import 앞쪽_표_구간


def main():
    표 = "| 비목 | 정의 |\n| --- | --- |\n| 항목 | ① 표 안의 내용 |\n"
    본문 = 표 + "\n제36조(사업비 비목) ① 비목은 표-10과 같다.\n< 표-10 사업비 비목 >\n② 다른 항이다."
    시작, 끝 = 앞쪽_표_구간(본문, "제36조", "①표-10")
    assert 본문[시작:끝] == 표
    assert 앞쪽_표_구간(본문, "제36조", "표-10") == (시작, 끝)
    실패 = [
        (본문, "제36조", "①표-11"),
        (본문, "제37조", "①표-10"),
        (본문, "제36조", "②표-10"),
        (본문.replace("표-10과", "표-11과"), "제36조", "①표-10"),
        (본문.replace("② 다른 항이다.", "② 표-10도 따른다."), "제36조", "표-10"),
        (본문.replace("① 비목", "비목"), "제36조", "표-10"),
        (본문.replace("< 표-10 사업비 비목 >", "< 표-10 사업비 비목 > < 표-11 다른 표 >"), "제36조", "①표-10"),
        (본문.replace("| --- | --- |", "| 구분 | 구분 |"), "제36조", "①표-10"),
        (본문.replace("\n제36조", "\n관계없는 문장\n제36조"), "제36조", "①표-10"),
    ]
    for 인자 in 실패:
        try:
            앞쪽_표_구간(*인자)
        except ValueError:
            continue
        raise AssertionError("모호한 표 위치가 통과됨")
    print("앞쪽 표 원문 위치 검사 통과")


if __name__ == "__main__":
    main()


def 괄호_표제_검사():
    """초격차 제18조 형식: ② 평문 참조 「아래 표-1」, 표제 `< (표-1) … >`, 표는 ③ 앞까지."""
    from ontology_table_evidence import 내부_표_구간
    from ontology_norm import 별지_행_내용
    본문 = ("제18조(사업비 구성 및 집행) ① 기준은 지침에 따른다.\n"
          "② 사업비 구성은 아래 표-1와 같으며 다음 각 호에 따른다.\n1.견품 재료비\n"
          "< (표-1) 창업기업등 사업비 구성 >\n총 사업비 정부지원사업비\n100% 70% 미만\n"
          "③ 연차별 협약을 체결하는 경우 소급 적용할 수 있다.\n")
    시작, 끝 = 내부_표_구간(본문, "제18조", "②표-1")
    assert 본문[시작:끝].startswith("< (표-1)") and "③" not in 본문[시작:끝]
    for 틀림 in (본문.replace("아래 표-1와", "아래와"), 본문.replace("③ 연차별", "연차별")):
        try:
            내부_표_구간(틀림, "제18조", "②표-1")
            raise AssertionError("참조·끝 경계가 없는데 통과")
        except ValueError:
            pass
    # 창업중심 참고3 형식: 괄호 붙은 비목 이름, 유의사항이 기준 칸에 합쳐진 비목
    표 = ("창업중심대학 창업기업 사업비 집행기준\n| 비목 | 구분 | 내용 |\n| --- | --- | --- |\n"
         "| 재료비 | 기 준 | 재료 기준 ※ 맞춤 제작은 외주용역비 |\n"
         "| 외주용역비 | 기 준 | 외주 기준 |\n|  | 유 의 사항 | 외주 유의 |\n"
         "| 기계장치 (공구·기구,비품, SW등) | 기 준 | 기계 기준 |\n")
    assert "맞춤 제작" in (별지_행_내용(표, "/재료비/유의사항") or "")
    assert 별지_행_내용(표, "/외주용역비/유의사항") == "외주 유의"
    assert 별지_행_내용(표, "/기계장치/기준") == "기계 기준"
    assert 별지_행_내용(표.replace("창업중심대학 창업기업 사업비 집행기준", ""), "/재료비/유의사항") is None
    # 대체 칸은 그 위치의 저장 발췌가 칸 안에 있을 때만 위치로 인정한다.
    import ontology_evidence as 검증
    assert 별지_행_내용(표, "/재료비/유의사항", 대체=False) is None
    assert 검증._위치_확인(표, "/재료비/유의사항", "참고3", ["맞춤 제작은 외주용역비"])
    assert not 검증._위치_확인(표, "/재료비/유의사항", "참고3", ["다른 칸에 있는 문장"])
    assert not 검증._위치_확인(표, "/재료비/유의사항", "참고3", None)


괄호_표제_검사()
print("괄호 표제·참고3 위치 검사 통과")
