# -*- coding: utf-8 -*-
"""앞쪽 표의 원문 좌표와 모호한 입력의 실패를 검사한다."""
from ontology_table_evidence import 앞쪽_표_구간


def main():
    표 = "| 비목 | 정의 |\n| --- | --- |\n| 항목 | ① 표 안의 내용 |\n"
    본문 = 표 + "\n제36조(사업비 비목) ① 비목은 표-10과 같다.\n< 표-10 사업비 비목 >\n② 다른 항이다."
    시작, 끝 = 앞쪽_표_구간(본문, "제36조", "①표-10")
    assert 본문[시작:끝] == 표
    assert 앞쪽_표_구간(본문, "제36조", "표-10") == (시작, 끝)
    실패 = [
        (본문, "제36조", "①표-11"),
        (본문, "제37조", "①표-10"),
        (본문, "제36조", "②표-10"),
        (본문.replace("표-10과", "표-11과"), "제36조", "①표-10"),
        (본문.replace("② 다른 항이다.", "② 표-10도 따른다."), "제36조", "표-10"),
        (본문.replace("① 비목", "비목"), "제36조", "표-10"),
        (본문.replace("< 표-10 사업비 비목 >", "< 표-10 사업비 비목 > < 표-11 다른 표 >"), "제36조", "①표-10"),
        (본문.replace("| --- | --- |", "| 구분 | 구분 |"), "제36조", "①표-10"),
        (본문.replace("\n제36조", "\n관계없는 문장\n제36조"), "제36조", "①표-10"),
    ]
    for 인자 in 실패:
        try:
            앞쪽_표_구간(*인자)
        except ValueError:
            continue
        raise AssertionError("모호한 표 위치가 통과됨")
    print("앞쪽 표 원문 위치 검사 통과")


if __name__ == "__main__":
    main()
