def 검사(rows: list[tuple[str, str, str]], 비목집합: set[str]) -> list[str]:
    """적재 전 자기검사. 통과 못 하면 넣지 않는다."""
    from rule_lookup import _norm

    문제 = []
    본, 정규본 = {}, {}
    for 상품명, 비목, 출처 in rows:
        if 비목 not in 비목집합:
            문제.append(f"어휘집에 없는 비목 '{비목}' ({상품명})")
        if 상품명 in 본:
            문제.append(f"상품명 중복 '{상품명}' → {본[상품명]} / {비목}")
        본[상품명] = 비목
        n = _norm(상품명)
        if not n:
            문제.append(f"정규형이 빈 문자열 '{상품명}'")
        elif n in 정규본 and 정규본[n][1] != 비목:
            문제.append(f"정규형 충돌 '{n}': {정규본[n][0]}→{정규본[n][1]} / {상품명}→{비목}")
        else:
            정규본.setdefault(n, (상품명, 비목))
        if not 출처:
            문제.append(f"출처 없음 '{상품명}'")
    for 상품명, _ in _제외:
        if 상품명 in 본:
            문제.append(f"_제외 목록에 있는데 적재 목록에도 있다 '{상품명}'")
    return 문제


