#    따로 둔다. 키 맨 앞의 숫자가 조번호다("11." · "18." 등) — 여기서 뽑아 대조한다.
_조번호_접두 = re.compile(r"^(\d+\.)")

# 🔴 실측(2026-09-06)으로 `rule_lookup._norm()` 을 긴 인용문에 그대로 쓰면 **14/14 전부
#    실패**했다 — 원인은 검사기가 아니라 `_norm()` 의 조사떼기다. PDF 줄바꿈이 단어
#    중간을 끊으면("...1만원 이\n내에서...") 공백 분리로 "이"·"내에서" 두 토큰이 되고,
#    "내에서"는 "에서" josa 를 떼도 어간이 "내"(1자)뿐이라 안 떨어지는데, 원본처럼
#    끊기지 않은 "이내에서" 는 "이내"+"에서" 로 갈라져 조사가 떨어져 나간다 — «같은 말이
#    줄바꿈 여부에 따라 다른 정규형»이 되는 것이다. 인용문 대조엔 조사떼기가 필요
#    없으므로(원본 그대로인지만 보면 된다) 구두점·공백만 지우고 조사는 안 뗀다.
# 🔴 실측(2026-09-06, ai-50 확인 + DB 직접 재확인) — 쪽번호("- 83 -")가 PDF 추출 시
#    페이지 경계에서 문장 «중간»에 그대로 끼어든다("...첨부하지\n- 83 -\n구 분 주요내용\n
#    않은..."). 인용문 대조엔 원문 그대로의 쪽번호가 있을 리 없으니 안전하게 지운다.
#    (표 셀의 세로 병합 라벨이 문장 중간에 새는 것도 같은 종류의 잡음이지만("연구시설·
#    \n구재료비\n장비") 이건 일반 규칙으로 못 걷어낸다 — 임의로 지우면 진짜 다른 자리의
#    짧은 비목명까지 지울 위험이 있다. 그 경우는 조각검증이 실패로 남기고 사람이 본다.)
_쪽번호 = re.compile(r"-\s*\d{1,4}\s*-")


def _norm_발췌(s: str) -> str:
    s = rule_lookup._nfkc(s or "").lower()
    s = _쪽번호.sub("", s)
    return rule_lookup._구두점.sub("", s)


# "1. ... 2. ... 3. ..." 처럼 항목을 이어붙인 인용문 — 조 사이에 각주·페이지번호가
# 끼어 있으면(실측: TIPS 조 11 에 "- 46 -" 쪽번호가 문단 중간에 박혀 있다) 전체
# 연속매칭은 실패해도 항목 «각각»은 원문에 있을 수 있다. 그 경우를 구분해서 보고한다.
_번호마커 = re.compile(r"(?:(?<=^)|(?<=\s))\d{1,2}\.\s+")


def _분절(s: str) -> list[str]:
    parts = [p.strip() for p in _번호마커.split(s) if p.strip()]
    return parts if len(parts) > 1 else [s]


def 근거원문_발췌_검산(cur, 파일: dict) -> list[dict]:
    """파일의 `근거원문_발췌` 각 항목이 그 조(TIPS) 본문 안에 있는가.

    전체가 한 덩어리로 안 붙으면 번호매김 항목 단위로 쪼개 다시 본다 — 완전 실패와
    "항목은 다 있는데 사이에 각주·쪽번호가 끼어 연속으로 안 붙는 것"을 가른다.
    """
    out = []
    for 키, 텍스트 in (파일.get("근거원문_발췌") or {}).items():
        m = _조번호_접두.match(키)
        if not m:
            out.append({"키": 키, "결과": None, "이유": "키에서 조번호를 못 뽑음"})
            continue
        조 = m.group(1)
        본문 = _조문본문(cur, tips=True, 조번호=조)
        nb = _norm_발췌(본문)
        if bool(본문) and _norm_발췌(텍스트) in nb:
            out.append({"키": 키, "조번호": 조, "결과": True})
            continue
        분절 = _분절(텍스트)
        if len(분절) > 1:
            조각결과 = [_norm_발췌(p) in nb for p in 분절]
            전부 = all(조각결과)
            out.append({"키": 키, "조번호": 조,
                        "결과": True if 전부 else None,
                        "판정": "조각별 전부 일치(연속 아님 — 사이에 각주·쪽번호 등)"
                                if 전부 else f"조각 {sum(조각결과)}/{len(조각결과)}만 일치",
                        "불일치조각": [분절[i][:40] for i, ok in enumerate(조각결과) if not ok]})
        else:
            out.append({"키": 키, "조번호": 조, "결과": False,
                        "이유": "발췌가 조 본문 어디에도 없다(조각화도 안 됨)",
                        "본문길이": len(본문)})
    return out


def 근거조_실재확인(cur, row: dict) -> dict:
    """행이 인용한 `근거` 조번호가 실제로 TIPS 문서에 (빈 본문이 아니게) 존재하는가.

    "발췌가 그 안에 있다"는 위 `근거원문_발췌_검산`(파일 단위)이 맡고, 여기는 그보다
    약한 사실확인이다 — 존재 안 하는 조번호를 근거로 다는 사고를 잡는다.
    """
    근거 = row.get("근거") or []
    if not 근거:
        return {"결과": None, "이유": "근거가 없다"}
    대조 = []
    for g in 근거:
        조 = g.get("조번호")
        if not 조 or "TIPS" not in str(g.get("doc_id") or ""):
            continue                          # L1 근거 조는 ⑤ 에서 따로 본다
        본문 = _조문본문(cur, tips=True, 조번호=조)
        대조.append({"조번호": 조, "실재": bool(본문)})
    if not 대조:
        return {"결과": None, "이유": "TIPS 문서를 가리키는 근거가 없다"}
    return {"결과": all(x["실재"] for x in 대조), "대조": 대조}


