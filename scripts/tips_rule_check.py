def _조문본문(cur, *, tips: bool, 조번호: str, _캐시: dict = {}) -> str:
    """해당 조의 active 청크를 chunk_id 순으로 이어붙인다. 없으면 빈 문자열."""
    키 = ("tips" if tips else "l1", 조번호)
    if 키 in _캐시:
        return _캐시[키]
    if tips:
        cur.execute(
            "SELECT text FROM corpus.chunks WHERE array_to_string(사업명,',') ILIKE %s "
            "AND status='active' AND 조번호 = %s ORDER BY chunk_id",
            [f"%{TIPS_사업명}%", 조번호])
    else:
        cur.execute(
            "SELECT text FROM corpus.chunks WHERE doc_id = %s AND status='active' "
            "AND 조번호 = %s ORDER BY chunk_id",
            [L1_DOC_ID, 조번호])
    본문 = " ".join(r[0] for r in cur.fetchall())
    _캐시[키] = 본문
    return 본문


