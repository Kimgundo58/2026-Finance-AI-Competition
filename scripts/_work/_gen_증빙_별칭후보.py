def main() -> None:
    with psycopg.connect(DSN) as conn:
        csv_names = {r[0] for r in conn.execute(
            "SELECT 증빙명 FROM corpus.evidence_sources").fetchall()}
        rule_names = {r[0] for r in conn.execute(
            "SELECT DISTINCT e FROM corpus.rules, unnest(증빙) e").fetchall()}
        사용처 = {}
        for r in rule_names - csv_names:
            사용처[r] = [f"{a}/{b}" for a, b in conn.execute(
                "SELECT 사업명, 비목 FROM corpus.rules WHERE %s = ANY(증빙) "
                "ORDER BY 1,2", (r,)).fetchall()]

    미일치 = set(사용처)
    표_대상 = {c["rules"] for c in 별칭후보}

    # 게이트 — 표가 라이브 DB 와 어긋나면 낡은 산출물을 내보내지 않는다.
    문제 = False
    for x in sorted(미일치 - 표_대상):
        print(f"🔴 표에 없는 미일치: {x!r}"); 문제 = True
    for x in sorted(표_대상 - 미일치):
        print(f"🔴 표에는 있으나 이미 일치하거나 사라진 값: {x!r}"); 문제 = True
    if 문제:
        sys.exit("표가 낡았다. 갱신 후 다시 돌려라.")

    # CSV 쪽 대상이 실재하는가 (별칭이 허구를 가리키면 안 된다)
    for c in 별칭후보:
        if c["csv"] and c["csv"] not in csv_names:
            sys.exit(f"🔴 별칭 대상이 CSV 에 없다: {c['csv']!r}")

    항목 = []
    for c in sorted(별칭후보, key=lambda x: (x["신뢰도"] != "높음", x["rules"])):
        항목.append({
            "rules_증빙": c["rules"],
            "evidence_증빙명": c["csv"],
            "신뢰도": c["신뢰도"],
            "근거": c["근거"],
            "비고": c.get("비고"),
            "사용처": 사용처[c["rules"]],
        })

    from collections import Counter
    분포 = Counter(c["신뢰도"] for c in 별칭후보)
    doc = {
        "생성": "scripts/_work/_gen_증빙_별칭후보.py",
        "기준일": "2026-08-31",
        "상태": "🔴 검수 전. 적용하지 않았다. corpus.rules·corpus.evidence_sources 둘 다 무변경.",
        "정본": "corpus.evidence_sources.증빙명 (124종) — 원본은 `공유받은 파일/증빙서류 종합.csv`",
        "대조_시점_실측": {
            "rules_증빙_distinct": len(rule_names),
            "evidence_증빙명": len(csv_names),
            "완전일치": len(rule_names & csv_names),
            "미일치": len(미일치),
            "완전일치율": f"{len(rule_names & csv_names) / len(rule_names) * 100:.0f}%",
            "별칭_적용시_예상_일치율":
                f"{(len(rule_names & csv_names) + 분포['높음'] + 분포['중간']) / len(rule_names) * 100:.0f}%",
        },
        "신뢰도_분포": dict(분포),
        "읽는 법": {
            "높음": "괄호 주석·수식어만 다르고 가리키는 서류가 같다. 그대로 적용해도 된다",
            "중간": "맥락 추론이 필요했다. 근거를 읽고 한 번 확인할 것",
            "판단필요": "대응처가 없다. 억지 매핑하지 않았다 — 오너 결정 대기",
        },
        "후보": 항목,
    }
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"미일치 {len(미일치)}종 · 표 {len(별칭후보)}종 — 일치")
    for k in ("높음", "중간", "판단필요"):
        if 분포.get(k):
            print(f"   {k:<5} {분포[k]}종")
    print(f"완전일치율 {doc['대조_시점_실측']['완전일치율']}"
          f" -> 별칭 적용 시 {doc['대조_시점_실측']['별칭_적용시_예상_일치율']} (예상)")
    print(f"산출: {OUT}")


if __name__ == "__main__":
    main()
