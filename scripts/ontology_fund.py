def 경로_자금(사업명: str | None, 비목_id: str | None) -> str | None:
    """확정 비목의 자금. 모두의 창업 밖은 None(거르지 않는다). 창업활동비가 아니면 사업비 비목이라 시제품제작비 쪽으로 본다."""
    if 사업명 != _사업 or not 비목_id:
        return None
    return 창업활동자금 if 비목_id == _창업활동자금_비목 else 시제품제작비


def 문의처(자금: str | None) -> str:
    """집행 전에 물어볼 곳(조사까지). 책자 p24-1 「이 항목에 돈을 써도 되는지 모르겠다 → 멘토기관 담당자(반드시 결제 전에)」."""
    return "멘토기관 담당자에게" if 자금 == 창업활동자금 else "주관기관에"


def 조문_자금(문서키: str | None, 조번호: str | None, 항호: str | None = None) -> str | None:
    """조문의 자금. 표에 없으면 None(공통). 항호는 항 기호로 시작하는 값(`②`, `②표-4`, `②#2`)만 본다."""
    if not 문서키:
        return None
    표 = _조문표.get(문서키) or {}
    if None in 표:
        return 표[None]
    if 조번호 in 표:
        return 표[조번호]
    항들 = _결정대기_항.get((문서키, 조번호 or ""))
    if 항들 and not 공통규범_창업활동자금_적용 and (항호 or "")[:1] in 항들 and 항호:
        return 시제품제작비
    return None


def 다른_자금(경로: str | None, 문서키: str | None, 조번호: str | None, 항호: str | None = None) -> bool:
    if not 경로:
        return False
    자금 = 조문_자금(문서키, 조번호, 항호)
    return 자금 is not None and 자금 != 경로


def 금지문장_항인가(경로: str | None, 문서키: str | None, 조번호: str | None, 키: str | None) -> bool:
    """창업활동자금 경로에서 다른 자금으로 빼지 않고 B2.6 에 남기는 금지 문장 항인가. 키는 문맥의 항 키(`⑧`, `/지급수수료/유의사항`)."""
    return 경로 == 창업활동자금 and (키 or "") in _금지문장_항.get((문서키 or "", 조번호 or ""), {})


def 금지문장_조문ID(경로: str | None) -> list[str]:
    """이 경로의 문맥 B2.6 에 넣을 금지 문장 항의 조문 ID. 창업활동자금 밖은 빈 목록."""
    if 경로 != 창업활동자금:
        return []
    return list(dict.fromkeys(f"조:{문서키}#{조번호}{항.split('#')[0]}" for (문서키, 조번호), 항들 in _금지문장_항.items() for 항 in 항들))


def 금지문장_조각(문서키: str | None, 조번호: str | None, 키: str | None, 조각: str) -> str:
    """금지 문장 항에서 판정 문맥에 넣을 글. 표의 정규식이 고른 글만 남긴다. 문장 중간에서 끊으면 ` …` 를 붙인다. 못 찾으면 그대로(금지 문장을 빠뜨리지 않는다)."""
    식들 = _금지문장_항.get((문서키 or "", 조번호 or ""), {}).get(키 or "")
    if not 식들:
        return 조각
    글 = " ".join(조각.split())
    고름 = [m.group(0).strip() for m in (re.search(식, 글) for 식 in 식들) if m]
    return " ".join(x if x.endswith(("다.", "불가", "…")) else f"{x} …" for x in 고름) if 고름 else 조각


def _다른_자금_조문ID(경로: str | None, 조문id: str) -> bool:
    if not 조문id.startswith("조:"):
        return False
    풀이 = 조문ID_풀이(조문id)
    return 다른_자금(경로, 풀이["문서키"], 풀이["조번호"], 풀이["항호"])


def 근거행_거르기(근거행: list[dict], 경로: str | None, 문서키표: dict[str, str]) -> list[dict]:
    """다른 자금 조문의 행을 빼고, 남은 행의 근거 경로에서 다른 자금 조문을 뗀다(화면 "근거 경로"). 문서키표 = doc_id → 문서키."""
    if not 경로:
        return 근거행
    out: list[dict] = []
    for 행 in 근거행:
        if 다른_자금(경로, 문서키표.get(행.get("doc_id")), 행.get("조번호"), 행.get("항호")):
            continue
        새행 = dict(행)
        for 칸 in ("경로", "우선경로"):
            if 새행.get(칸):
                새행[칸] = [i for i in 새행[칸] if not _다른_자금_조문ID(경로, i)]
        out.append(새행)
    return out


def 공통규범_나누기(경로: str | None, 규범들: list[dict], 노드들: set[str]) -> tuple[list[dict], list[dict]]:
    """(쓰는 규범, 자금 적용 미정 규범). 창업활동자금 경로에서 `비목:창업/*` 로만 닿는 규범이 뒤쪽이다. 우선순위 규범은 L3 적용 순서에 쓰여 남긴다."""
    if 경로 != 창업활동자금 or 공통규범_창업활동자금_적용:
        return 규범들, []
    쓰는: list[dict] = []
    미정: list[dict] = []
    for n in 규범들:
        직접 = (set(n.get("대상") or []) & 노드들) - {_모든비목}
        (쓰는 if 직접 or n.get("종류") == "우선순위" else 미정).append(n)
    return 쓰는, 미정


def 공통_품목규범(경로: str | None, 규범들: list[dict]) -> list[dict]:
    """경로 밖 품목 규범 중 자금 적용 미정인 것(창업활동자금 경로에서 `비목:창업/*` 아래 품목. 부채 상환 등)."""
    if 경로 != 창업활동자금 or 공통규범_창업활동자금_적용:
        return []
    return [n for n in 규범들 if not any("창업활동자금" in v for v in n.get("대상") or [])]


