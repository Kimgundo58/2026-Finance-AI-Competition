def main() -> None:
    데이터 = [(code, None, 비목, 구분, 항목, 설명, 오프셋,
              json.dumps([{"doc_id": 지침, "조번호": j} for j in 조들], ensure_ascii=False),
              True, 검수자, 검수일)
             for code, 비목, 구분, 항목, 설명, 오프셋, 조들 in 항목들]

    codes = [d[0] for d in 데이터]
    assert len(codes) == len(set(codes)), "code 중복"

    with psycopg.connect(DSN) as conn:
        # 🔴 TRUNCATE 금지. `tenant.plan_tasks.코드` 가 이 테이블의 code 를 FK 로 참조한다.
        #    TRUNCATE ... CASCADE 는 **사용자가 체크해 둔 진행상황을 통째로 지운다** —
        #    이 테이블이 존재하는 이유(재판정 간 진행상황 유지)를 정면으로 깨는 짓이다.
        #    upsert 로 갱신하고, 목록에서 빠진 code 는 DELETE 로 지운다.
        #    참조 중인 code 를 지우려 하면 FK 가 막아 준다 — 조용히 날아가지 않는다.
        with conn.cursor() as cur:
            cur.executemany("""
                INSERT INTO corpus.check_items
                  (code, 사업명, 비목, 구분, 항목, 설명, 기본_오프셋일,
                   근거, verified, 검수자, 검수일)
                VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
                ON CONFLICT (code) DO UPDATE SET
                  사업명=EXCLUDED.사업명, 비목=EXCLUDED.비목, 구분=EXCLUDED.구분,
                  항목=EXCLUDED.항목, 설명=EXCLUDED.설명,
                  기본_오프셋일=EXCLUDED.기본_오프셋일, 근거=EXCLUDED.근거,
                  verified=EXCLUDED.verified, 검수자=EXCLUDED.검수자,
                  검수일=EXCLUDED.검수일""", 데이터)
            버려질 = cur.execute(
                "SELECT code FROM corpus.check_items WHERE code <> ALL(%s)",
                (codes,)).fetchall()
            if 버려질:
                print(f"목록에서 빠진 code {len(버려질)}개 삭제: {[x[0] for x in 버려질]}")
                cur.execute("DELETE FROM corpus.check_items WHERE code <> ALL(%s)", (codes,))
        conn.commit()

        n, 전, 후 = conn.execute("""SELECT count(*),
            count(*) FILTER (WHERE 구분='결제전'), count(*) FILTER (WHERE 구분='결제후')
            FROM check_items""").fetchone()
        print(f"check_items {n}행 (결제전 {전} · 결제후 {후})")

        print("\n== 비목별")
        for 비목, c in conn.execute(
                "SELECT coalesce(비목,'(전 비목 공통)'), count(*) FROM check_items "
                "GROUP BY 1 ORDER BY 2 DESC, 1").fetchall():
            print(f"   {비목:<22} {c}")

        # 🔴 rules 와 같은 게이트. 근거가 실재하지 않으면 그 항목의 인용은 허구다.
        dang = conn.execute("""
            SELECT DISTINCT g->>'doc_id', g->>'조번호'
              FROM check_items r, jsonb_array_elements(r.근거) g
             WHERE NOT EXISTS (SELECT 1 FROM corpus.doc_articles a
                               WHERE a.doc_id=g->>'doc_id' AND a.조번호=g->>'조번호')""").fetchall()
        print(f"\n== 근거 dangling: {len(dang)}")
        for d in dang:
            print("   🔴", d)

        # 비목은 rules 와 같은 조회 키여야 한다 (NULL 은 전 비목 공통이라 제외)
        밖 = conn.execute("""
            SELECT DISTINCT c.비목 FROM check_items c
             WHERE c.비목 IS NOT NULL
               AND NOT EXISTS (SELECT 1 FROM corpus.rules r WHERE r.비목 = c.비목)""").fetchall()
        print(f"== rules 에 없는 비목: {len(밖)}" + ("  🔴" if 밖 else ""))
        for x in 밖:
            print("   🔴", x[0])

        print(f"== corpus.rules: {conn.execute('SELECT count(*) FROM rules').fetchone()[0]}행 (읽기만 했다)")


if __name__ == "__main__":
    main()
