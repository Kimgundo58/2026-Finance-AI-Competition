def _부호검사(행들: list[dict]) -> list[str]:
    """E5 규약: 결제전 ≤ 0 · 결제후 ≥ 0. 어긋나면 과거/미래로 잘못 꽂힌다."""
    나쁨 = []
    for r in 행들:
        off = r["기본_오프셋일"]
        if off is None:
            continue
        if r["구분"] == "결제전" and off > 0:
            나쁨.append(f"{r['code']}: 결제전인데 오프셋 +{off} (집행 후로 꽂힌다)")
        if r["구분"] == "결제후" and off < 0:
            나쁨.append(f"{r['code']}: 결제후인데 오프셋 {off} (집행 전으로 꽂힌다)")
    return 나쁨


_배수 = {"억원": 100_000_000, "천만원": 10_000_000, "백만원": 1_000_000,
        "만원": 10_000, "원": 1}
_금액re = re.compile(r"(?<![\d,])([\d,]+)\s*(억원|천만원|백만원|만원|원)")
# 금액이 아닌 수치 주장 — 표기 그대로 대조한다.  '4대'(4대보험)는 이름이라 뺀다
_수치re = re.compile(r"(\d+\s*%|\d+\s*년|\d+\s*개월|\d+\s*일간|\d+인|\d+대(?!사회))")


def _금액집합(t: str) -> set[int]:
    """"30만원" 과 "300,000원" 을 같은 값으로 본다. 표기차로 오탐하면 통과 조건을 못 믿는다."""
    out = set()
    for 수, 단위 in _금액re.findall(t):
        try:
            out.add(int(수.replace(",", "")) * _배수[단위])
        except ValueError:
            pass
    # "12만5천원" 같은 복합 표기
    for m in re.finditer(r"(\d+)\s*만\s*(\d+)\s*천원", t):
        out.add(int(m.group(1)) * 10_000 + int(m.group(2)) * 1_000)
    return out


def _수치접지검사(cur, 행들: list[dict]) -> list[str]:
    """🔴 항목·설명이 말하는 수치가 인용 조문 본문에 실제로 있는가.

    `멘토링한도확인` 이 L1 제42조를 근거로 달고 "30만원" 을 말하던 것을 잡은 통과 조건이다.
    인용을 제품의 신뢰 근거로 쓰는 이상, 인용한 조문에 없는 숫자를 말하면
    그 순간 인용이 장식이 된다.
    """
    나쁨 = []
    캐시: dict[tuple[str, str], str] = {}
    for r in 행들:
        본문들 = []
        for g in json.loads(r["근거"]):
            키 = (g["doc_id"], g["조번호"])
            if 키 not in 캐시:
                row = cur.execute(
                    "SELECT 본문 FROM corpus.doc_articles WHERE doc_id=%s AND 조번호=%s",
                    키).fetchone()
                캐시[키] = row[0] if row else ""
            본문들.append(캐시[키])
        근거본문 = " ".join(본문들)
        주장 = f"{r['항목']} {r['설명'] or ''}"

        빠진금액 = _금액집합(주장) - _금액집합(근거본문)
        if 빠진금액:
            나쁨.append(f"{r['code']}: 금액 {sorted(빠진금액)}원 이 근거 조문에 없다 "
                        f"({[g['조번호'] for g in json.loads(r['근거'])]})")
        근거정규 = re.sub(r"\s+", "", 근거본문)
        빠진수치 = [x for x in set(_수치re.findall(주장))
                  if re.sub(r"\s+", "", x) not in 근거정규]
        if 빠진수치:
            나쁨.append(f"{r['code']}: 수치 {빠진수치} 가 근거 조문에 없다")
    return 나쁨


def _증빙접지검사(cur) -> tuple[int, int, list[str]]:
    """E6. `rules.증빙` 이름이 `evidence_sources` 로 해소되는가 (화면 6 발급처 안내).

    🔴 착수 시 받은 전제는 "표기차 14 + 복합문자열 12 = 26종이 뚫려 있다" 였는데
       **실측하니 71종 중 70종이 완전일치하고 1종만 남았다.** 26 은
       `02_frontend.sql` 주석이 쓰인 시점(rules 19행 · 증빙 49종)의 숫자다.
       그 주석이 처방한 작업("복합 문자열을 낱개로 쪼개 재적재")이 `seed_rules.py`
       개편(19행 → 54행 · 증빙 49 → 71종)에서 이미 끝나 있었다.
       그래서 오늘 별칭 테이블을 새로 만들지 않는다 — 만들면 26개의 빈 행이 된다.

    대신 **통과 조건으로 남긴다.** 다음에 `seed_rules.py` 가 해소 안 되는 증빙명을
    들여오면 조용히 화면 6 이 뚫리는 대신 여기서 걸린다.
    """
    미해소 = [x[0] for x in cur.execute("""
        SELECT DISTINCT x FROM corpus.rules r, unnest(r.증빙) x
         WHERE x IS NOT NULL AND x <> ''
           AND NOT EXISTS (SELECT 1 FROM corpus.evidence_sources e WHERE e.증빙명 = x)
         ORDER BY 1""").fetchall()]
    전체 = cur.execute(
        "SELECT count(DISTINCT x) FROM corpus.rules r, unnest(r.증빙) x "
        " WHERE x IS NOT NULL AND x <> ''").fetchone()[0]
    return 전체, 전체 - len(미해소), 미해소


def _끊긴참조검사(cur) -> list[tuple]:
    return cur.execute("""
        SELECT DISTINCT g->>'doc_id', g->>'조번호'
          FROM corpus.check_items r, jsonb_array_elements(r.근거) g
         WHERE NOT EXISTS (SELECT 1 FROM corpus.doc_articles a
                           WHERE a.doc_id = g->>'doc_id' AND a.조번호 = g->>'조번호')
    """).fetchall()


