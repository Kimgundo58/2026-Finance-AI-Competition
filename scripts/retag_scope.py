참조확장전용_집합: dict[str, str] = {
    d: 그룹 for 그룹, _근거, docs in CLOSURE for d in docs
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="UPDATE 없이 계획만 출력")
    ap.add_argument("--revert", action="store_true", help="전부 '진입점' 으로 되돌린다")
    a = ap.parse_args()

    # 하드코딩 목록 자체의 자기검증 — 중복 doc_id 는 근거가 둘이라는 뜻이다
    if len(참조확장전용_집합) != sum(len(d) for _, _, d in CLOSURE):
        sys.exit("CLOSURE 안에 중복 doc_id 가 있다.")
    if 겹침 := set(KEEP) & set(참조확장전용_집합):
        sys.exit(f"KEEP 과 CLOSURE 에 동시 등장: {겹침}")

    with psycopg.connect(DSN) as conn:
        cur = conn.cursor()

        if a.revert:
            cur.execute("UPDATE corpus.documents SET retrieval_scope='진입점' "
                        "WHERE retrieval_scope <> '진입점'")
            n_d = cur.rowcount
            cur.execute("UPDATE corpus.chunks SET retrieval_scope='진입점' "
                        "WHERE retrieval_scope <> '진입점'")
            print(f"되돌림 — documents {n_d}건 · chunks {cur.rowcount}건")
            conn.commit()
            return

        # active L1 은 KEEP 이나 CLOSURE 중 하나에 반드시 있어야 한다.
        # 없으면 중단 — 새로 들어온 문서가 판단 없이 진입점으로 남는 걸 막는다.
        cur.execute("SELECT doc_id FROM corpus.documents "
                    "WHERE layer='L1' AND status='active' ORDER BY doc_id")
        active_l1 = [r[0] for r in cur.fetchall()]
        미분류 = [d for d in active_l1 if d not in KEEP and d not in 참조확장전용_집합]
        if 미분류:
            print("🔴 분류되지 않은 active L1 문서가 있다. KEEP 이나 CLOSURE 에 근거와 함께 "
                  "추가할 것:", file=sys.stderr)
            for d in 미분류:
                print(f"    {d}", file=sys.stderr)
            sys.exit(1)
        유령 = [d for d in (set(KEEP) | set(참조확장전용_집합)) if d not in active_l1]
        if 유령:
            print(f"⚠️  목록에는 있으나 DB active L1 에 없는 doc_id {len(유령)}건 "
                  "(개정으로 doc_id 가 바뀌었을 수 있다):")
            for d in sorted(유령):
                print(f"    {d}")

        # L2 active 는 전부 세부관리기준/총괄운영지침 -> 무조건 진입점. 확인만 하고 넘어간다
        cur.execute("SELECT count(*) FROM corpus.documents WHERE layer='L2' AND status='active'")
        print(f"L2 active {cur.fetchone()[0]}건 — 전부 진입점 유지 "
              "(세부관리기준·총괄운영지침은 정의상 진입점)")

        cur.execute("""SELECT d.doc_id, coalesce(c.n,0) FROM corpus.documents d
                       LEFT JOIN (SELECT doc_id, count(*) n FROM corpus.chunks GROUP BY 1) c
                              ON c.doc_id = d.doc_id
                        WHERE d.doc_id = ANY(%s)""", (list(참조확장전용_집합),))
        청크수 = dict(cur.fetchall())

        print(f"\n폐포전용 {len(참조확장전용_집합)}문서 "
              f"/ {sum(청크수.values())}청크  (KEEP {len(KEEP)}문서)")
        for 그룹, _근거, docs in CLOSURE:
            print(f"  {그룹:24} {len(docs):3}문서 {sum(청크수.get(d,0) for d in docs):6}청크")

        if a.dry_run:
            print("\n--dry-run — UPDATE 하지 않았다.")
            return

        cur.execute("UPDATE corpus.documents SET retrieval_scope='폐포전용' "
                    "WHERE doc_id = ANY(%s) AND retrieval_scope <> '폐포전용'",
                    (list(참조확장전용_집합),))
        print(f"\ndocuments UPDATE {cur.rowcount}건")

        # 🔴 chunks 는 documents 의 사본이다. 한쪽만 고치면 조용히 어긋난다 —
        #    조건 없이 documents 에서 통째로 내려받아 드리프트 자체를 없앤다.
        cur.execute("""UPDATE corpus.chunks c SET retrieval_scope = d.retrieval_scope
                         FROM corpus.documents d
                        WHERE c.doc_id = d.doc_id
                          AND c.retrieval_scope IS DISTINCT FROM d.retrieval_scope""")
        print(f"chunks   UPDATE {cur.rowcount}건 (documents 에서 동기화)")
        conn.commit()

        cur.execute("""SELECT count(*) FROM corpus.chunks
                        WHERE embedding IS NOT NULL AND status='active'
                          AND parse_quality='high' AND retrieval_scope='진입점'
                          AND layer IN ('L1','L2') AND 적용대상 IN ('창업기업','공통')""")
        print(f"판정 검색 후보 청크: {cur.fetchone()[0]}")


if __name__ == "__main__":
    main()
