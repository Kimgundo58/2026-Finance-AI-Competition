def _잠깐(대상_id: str, 규범들: list[dict]):
    """그 대상의 시험 규범을 잠시 바꾼다."""
    class 문맥:
        def __enter__(self):
            self.원 = 규범표[대상_id]
            규범표[대상_id] = 규범들

        def __exit__(self, *_):
            규범표[대상_id] = self.원
    return 문맥()


