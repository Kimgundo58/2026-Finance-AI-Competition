def _llm(프롬프트, 스키마, **k):
    _고정.호출수 += 1
    출력 = dict(_고정.출력)
    인용 = 출력.pop("인용", None)
    if callable(인용):                 # 프롬프트의 문장에서 고른다
        인용 = 인용(프롬프트)
    ids = (스키마["properties"]["인용"]["items"].get("enum") or [])[:1]
    인용 = 인용 or ids
    전제 = 출력.pop("전제", None)
    return {"해야할일": [], "인용": 인용, **출력,
            "전제": [{"사실": 전제, "근거조항": 인용[0], "매핑": [], "미충족시": "판단불가"}] if 전제 else []}, {"모델": "고정", "입력토큰": 0, "출력토큰": 0}


