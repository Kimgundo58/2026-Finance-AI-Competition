def 정본증빙(names: list[str]) -> list[str]:
    """배열 원소를 정본 증빙명으로 바꾸고 중복을 없앤다 (등장 순서 유지).

    중복이 생기는 경우가 실제로 있다 — 근로소득원천징수영수증/부 2종이 CSV 한 행으로 접힌다.
    """
    out: list[str] = []
    for n in names:
        v = _증빙_별칭.get(n, n)
        if v not in out:
            out.append(v)
    return out


