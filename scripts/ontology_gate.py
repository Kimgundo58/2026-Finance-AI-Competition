_한글자릿수 = dict(zip("일이삼사오육칠팔구", range(1, 10)))
_작은자리 = {"십": 10, "백": 100, "천": 1000}
_큰자리 = {"만": 10**4, "억": 10**8}


def _금액값(표현: str) -> float:
    """`3천5백만` · `12만5천` · `2,500,000` 을 값으로 푼다. 천 · 백은 뒤의 만 · 억에 묶인다."""
    합 = 구간 = 0.0
    for 수, 자리 in re.findall(r"(\d[\d,]*(?:\.\d+)?)?([억만천백])?", 표현):
        값 = float(수.replace(",", "")) if 수 else 0.0
        if 자리 in _작은자리:
            구간 += (값 or 1) * _작은자리[자리]
        elif 자리:
            합 += ((구간 + 값) or 1) * _큰자리[자리]
            구간 = 0.0
        else:
            구간 += 값
    return 합 + 구간


def _한글수_풀기(m: re.Match) -> str:
    합 = 구간 = 현재 = 0
    for 글자 in m.group(0):
        if 글자 in _한글자릿수:
            현재 = _한글자릿수[글자]
        elif 글자 in _작은자리:
            구간, 현재 = 구간 + (현재 or 1) * _작은자리[글자], 0
        else:
            합, 구간, 현재 = 합 + ((구간 + 현재) or 1) * _큰자리[글자], 0, 0
    return str(합 + 구간 + 현재)


def 금액집합(글: str | None) -> set[float]:
    """글 안의 돈 금액을 원 단위 값으로 모은다. `원` 이 붙거나, 만 · 억으로 끝나거나, 쉼표로 묶인 1만 이상인 수만 금액으로 본다(`1인` · `3회` · `2026년` 은 뺀다).
    `이백만원` 처럼 한글로만 쓴 수는 `원` 이 붙을 때만 읽는다(`수백만원` 은 값이 아니라 읽지 않는다)."""
    글 = re.sub(r"(?<=\d)\s+(?=[억만천백])|(?<=[억만천백])\s+(?=[\d만])|(?<=[\d억만천백십])\s+(?=원)", "", 글 or "")
    글 = re.sub(r"(?<![가-힣\d])[일이삼사오육칠팔구십백천만억]*[십백천만억](?=원)", _한글수_풀기, 글)
    out: set[float] = set()
    for m in _금액표현.finditer(글):
        표현, 값 = m.group(0), _금액값(m.group(0))
        if 글[m.end():m.end() + 1] == "원" or 표현.endswith(("억", "만")) or ("," in 표현 and 값 >= 10000):
            out.add(값)
    return out


def 요약_금액_허용(입력: dict, 규범들: list[dict], 글들: list[str | None]) -> set[float]:
    """요약에 써도 되는 금액: 입력 금액(부가세 환산 · 분모로 나눈 값 포함) · 입력 칸 · 글들(입력 문장 · 인용 원문) · 규범의 수치 · 발췌 · 조건 문장 · 그 규범 기준과 입력의 차액."""
    금액 = 입력.get("금액")
    허용: set[float] = set()
    try:
        금액 = float(금액) if 금액 is not None else None
    except (TypeError, ValueError):
        금액 = None
    if 금액 is not None:
        허용 |= {금액, 금액 * 1.1, 금액 / 1.1}
    for k in 입력키:
        try:
            허용.add(float(입력[k]))
        except (KeyError, TypeError, ValueError):
            pass
    for 글 in 글들:
        허용 |= 금액집합(글)
    for n in 규범들:
        수치 = n.get("수치") or {}
        if 수치.get("값") is not None and (수치.get("단위") or "원") == "원":
            허용.add(float(수치["값"]))
            if 금액 is not None:
                허용 |= {abs(금액 - float(수치["값"])), abs(금액 * 1.1 - float(수치["값"]))}
            값들, _ = _비교값들({**n, "수치": {**수치, "누적범위": None}}, 입력)
            허용 |= set(값들 or [])
        for g in (n.get("근거") or []):
            허용 |= 금액집합(g.get("발췌"))
        결과 = n.get("결과") or {}
        허용 |= 금액집합(결과.get("문장")) | 금액집합(결과.get("조건문장")) | 금액집합(_자연어조건(n))
    return 허용


def 요약_금액_불일치(요약: str | None, 입력: dict, 규범들: list[dict], 글들: list[str | None]) -> set[float]:
    """요약의 금액 중 입력 · 규범 · 인용 원문 값과 맞지 않는 것. 반올림 차이(0.5%)는 같은 값으로 본다."""
    허용 = 요약_금액_허용(입력, 규범들, 글들)
    return {v for v in 금액집합(요약) if not any(abs(v - h) <= max(1.0, h * 0.005) for h in 허용)}


def 화면_조건(g: dict) -> list[dict]:
    """게이트 조건 중 화면에 내는 것. 다른 수범자의 의무는 판정 문맥에만 남는다."""
    return [c for c in g.get("조건") or [] if c.get("구분") != "다른수범자"]


def 합치기(g: dict, llm판정: str | None) -> tuple[str, bool]:
    """5-6 "합치는 규칙". 코드 결과는 판정의 상한이다. 반환 (최종 판정, 코드가 낮췄는가)."""
    if g.get("종류") in ("금지", "한도초과"):
        return "불가", False
    if g.get("종류") == "부가세기준미정":
        return "판단불가", False
    if llm판정 == "가능" and g.get("상한") == "조건부":
        return "조건부", True
    return llm판정 or "판단불가", False


