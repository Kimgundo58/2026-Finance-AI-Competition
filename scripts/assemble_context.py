RE_항 = re.compile(r"[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]")


def _s(i: int) -> str:
    return f"S{i:02d}"


_전각 = str.maketrans({"<": "＜", ">": "＞"})
_RE_문장표식 = re.compile(r"\[\s*S(\d+)\s*\]")
_RE_줄머리_제목 = re.compile(r"(?m)^([ \t]*)#")


def 이스케이프(글: str | None) -> str:
    """규정 원문이 프롬프트 표식을 흉내 내지 못하게 바꾼다(새 경로, L1 · L2 · L3 모두).

    문장 표식 `[S01]` · 래퍼 끝 표식 · 줄머리 `#` · 꺾쇠만 비슷한 전각 문자로 바꾼다. 인용은 문장맵으로 DB 원문을 다시 읽어
    치환하므로 화면 원문에는 영향이 없다.
    """
    s = (글 or "").replace(래퍼_끝, "［규정 원문 끝］").translate(_전각)
    s = _RE_문장표식.sub(lambda m: f"［S{m.group(1)}］", s)
    return _RE_줄머리_제목.sub(r"\1＃", s)


def _자료(블록: str) -> str:
    """자료 블록 하나를 <자료> 태그로 감싼다. 안의 꺾쇠는 전각으로 바꿔 태그를 닫거나 새 태그를 흉내 내지 못하게 한다.

    문장 표식 `[S01]` 은 바꾸지 않는다(B4 의 「[S03]의 원문」 참조가 그대로 남아야 한다). B1~B3 은 이미 이스케이프돼 있다."""
    return f"<자료>\n{블록.strip().translate(_전각)}\n</자료>"


def 항_분할(본문: str) -> list[tuple[str | None, str]]:
    """조 본문을 (항 기호, 조각) 목록으로 나눈다. 항이 없으면 조 전체가 한 조각이다."""
    자리 = [m.start() for m in RE_항.finditer(본문 or "")]
    if not 자리:
        return [(None, (본문 or "").strip())]
    out = []
    항앞부분 = 본문[:자리[0]].strip()
    if 항앞부분:
        out.append((None, 항앞부분))
    for k, st in enumerate(자리):
        end = 자리[k + 1] if k + 1 < len(자리) else len(본문)
        조각 = 본문[st:end].strip()
        if 조각:
            out.append((조각[0], 조각))
    return out


