# -*- coding: utf-8 -*-
"""회귀 — **판단불가일 때 문의초안이 «실경로에서» 나오는가.**

    PYTHONIOENCODING=utf-8 python -m pytest tests/test_문의초안.py -q

🔴 이 파일이 막는 것은 «없던 값» 이 아니라 «목에만 있던 값» 이다.

    `문의초안` 은 목(`main.py:_목_판정`)에만 값이 박혀 있었고 **엔진에 만드는 코드가
    0줄**이었다. 그래서 실서버에서는 이벤트가 아예 안 나갔다. 자체점검조차
    `?목=판단불가` 로만 돌아 그 사실을 못 잡았다 — 초록이 결함을 가린 자리다.
    → 그래서 여기서는 **목을 통하지 않고** 함수를 직접 태우고, 한 번은 `_실_판정` 을
      스텁 오케로 «실제로» 통과시켜 키가 실리는지 본다.

🔴 두 번째 축은 «지어내지 않는가» 다. 빈 괄호·`None` 문자열·「제0조」·연속 공백이
   하나라도 남으면 문서 전체가 「AI 가 지어냈다」로 읽힌다 — 그러면 이 기능은 마이너스다.
   그래서 빈 필드 조합마다 **흔적 0** 을 검사한다.

■ LLM·DB·GPU 를 안 쓴다. `server/inquiry.py` 는 순수 함수다.
"""
from __future__ import annotations

import sys
import types
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT))

from server import inquiry                        # noqa: E402

정규화 = {"품목": "디자이너 업무용 노트북", "금액": 2500000}
인용 = [{"조번호": "제39조", "조제목": "기계장치",
        "doc_id": "L1_중소기업창업_지원사업_통합관리지침_제14차개정_20251223"}]
전제 = [{"사실": "협약 총액이 확인되지 않았다"},
       {"사실": "해당 품목의 비목이 확정되지 않았다"}]

# 🔴 「지어낸 흔적」의 목록. 하나라도 나오면 초안을 못 쓴다.
_흔적 = ("()", "( )", "None", "미상", "제0조", "  ", "[]", "{}")


def _흔적검사(문장: str) -> list[str]:
    return [x for x in _흔적 if x in 문장]


# ── ① 판정 4종 — 판단불가에서만 나온다 ──────────────────────────────

@pytest.mark.parametrize("판정", ["가능", "조건부", "불가"])
def test_판단불가가_아니면_안_만든다(판정):
    """🔴 만들어 두고 안 싣는 게 아니라 **안 만든다.** 실었는지 여부를 부르는 쪽의
    조건문에 맡기면, 그 조건문이 바뀌는 날 조용히 새 나간다."""
    assert inquiry.문의초안(정규화, 판정, 인용, 전제, "예비창업패키지") is None


def test_판단불가면_만든다():
    초안 = inquiry.문의초안(정규화, "판단불가", 인용, 전제, "예비창업패키지")
    assert 초안 and "디자이너 업무용 노트북(250만원)" in 초안
    assert 초안.startswith("안녕하세요. 예비창업패키지 참여기업입니다.")
    assert 초안.rstrip().endswith("확인 부탁드립니다. 감사합니다.")


# ── ② 🔴 빈 필드 조합 — 문장이 «깨지지» 않는가 ──────────────────────

@pytest.mark.parametrize("라벨,정규,c,t,사업", [
    ("인용 0건",      정규화, [],  전제, "예비창업패키지"),
    ("전제 0건",      정규화, 인용, [],  "예비창업패키지"),
    ("금액 없음",     {"품목": "노트북"}, [], 전제, "예비창업패키지"),
    ("사업명 없음",   정규화, [],  전제, None),
    ("품목·금액 없음", {},    인용, 전제, "예비창업패키지"),
    ("조제목 없음",   정규화, [{"조번호": "제39조", "doc_id": "L1_통합관리지침_20251223"}],
                     전제, "예비창업패키지"),
])
def test_필드가_비어도_문장이_안_깨진다(라벨, 정규, c, t, 사업):
    초안 = inquiry.문의초안(정규, "판단불가", c, t, 사업)
    assert 초안, f"{라벨}: 초안이 안 나왔다"
    남은 = _흔적검사(초안)
    assert not 남은, f"{라벨}: 지어낸 흔적 {남은} — {초안!r}"
    assert "\n\n\n" not in 초안, f"{라벨}: 빈 줄이 겹쳤다"
    for 줄 in 초안.split("\n"):
        assert 줄 == 줄.strip(), f"{라벨}: 줄 끝/앞 공백 — {줄!r}"


def test_조번호_없는_인용은_통째로_뺀다():
    """🔴 「제0조」·빈 괄호를 만드는 대신 그 인용을 «안 쓴다»."""
    초안 = inquiry.문의초안(정규화, "판단불가",
                        [{"조제목": "기계장치", "doc_id": "L1_통합관리지침_20251223"}],
                        [], "예비창업패키지")
    assert 초안 and "기준을 확인했습니다" not in 초안
    assert not _흔적검사(초안)


def test_전부_비면_None_이다():
    """인사말과 맺음말만 남은 초안은 없느니만 못하다."""
    assert inquiry.문의초안({}, "판단불가", [], [], None) is None
    assert inquiry.문의초안({}, "판단불가", [{"조제목": "x"}], [], None) is None


def test_전제_사실을_한_글자도_안_바꾼다():
    """🔴 어미를 고치는 건 곧 «문장을 지어내는» 것이다. 실제 `사실` 은 이미 다-로 끝나는
    완결문이라(실측), 「~인지 확인이 필요합니다」로 이으면 **뜻이 뒤집힌다**
    (「확인되지 않았는지 확인이 필요합니다」).

    🔴 **«부분 문자열» 로 재면 안 잡힌다.** 처음에 `사실 in 초안` 으로 썼다가 어미를
       덧붙이는 돌연변이를 **놓쳤다** — 덧붙여도 원문은 여전히 부분 문자열이라 초록이었다.
       줄 «전체» 가 정확히 `- {사실}` 인지를 봐야 잡힌다. 초록이 증거가 아닌 자리가
       코드에만 있는 게 아니라 **테스트의 판별식에도 있다.**
    """
    초안 = inquiry.문의초안(정규화, "판단불가", [], 전제, "예비창업패키지")
    줄들 = [x for x in 초안.split("\n") if x.startswith("- ")]
    assert 줄들 == [f"- {t['사실']}" for t in 전제], (
        f"전제 줄이 원문과 다르다 — 어미를 덧붙였거나 손댔다: {줄들}")


def test_규정_원문이_초안에_안_섞인다():
    """🔴 CLAUDE.md: 「인용은 S번호 추출 — LLM 이 원문을 쓰지 않는다」.
    코드 조립본도 같은 규칙을 진다. 인용에서 쓰는 것은 **조번호·조제목까지**이고
    `원문` 필드는 한 글자도 나가면 안 된다."""
    원문 = "기계장치는 사업계획서에 명시된 범위에서 취득할 수 있으며, 1인 1대를 원칙으로 한다."
    초안 = inquiry.문의초안(
        정규화, "판단불가",
        [{"조번호": "제39조", "조제목": "기계장치", "원문": 원문,
          "doc_id": "L1_중소기업창업_지원사업_통합관리지침_제14차개정_20251223"}],
        전제, "예비창업패키지")
    assert 초안 and "제39조(기계장치)" in 초안
    assert 원문 not in 초안
    for 조각 in ("사업계획서에 명시된", "1인 1대", "원칙으로 한다"):
        assert 조각 not in 초안, f"규정 원문 조각이 초안에 실렸다: {조각!r}"


def test_금액_표기():
    assert inquiry.금액표기(2500000) == "250만원"
    assert inquiry.금액표기(1234567) == "1,234,567원"      # 만 단위로 안 떨어진다
    assert inquiry.금액표기(100000000) == "1억원"
    for 없음 in (None, 0, -1, "", "abc", True):
        assert inquiry.금액표기(없음) is None, f"{없음!r} 에서 값이 나왔다"


# ── ③ 🔴 실경로 — 목을 통하지 않는다 ────────────────────────────────

@pytest.fixture
def 스텁오케(monkeypatch):
    """`_실_판정` 이 부르는 `orchestrate.판정` 만 갈아끼운다. LLM·DB·GPU 안 쓴다.

    🔴 `?목=` 으로 재면 이 파일이 아무것도 못 잡는다 — 목에는 `문의초안` 이 이미
       박혀 있어서, 엔진에 만드는 코드가 0줄이어도 초록이 나온다. 그게 이 결함이
       오래 안 잡힌 이유다.
    """
    가짜 = types.ModuleType("orchestrate")
    가짜.판정 = lambda *a, **k: {
        "판정": "판단불가", "요약": "근거를 찾지 못했습니다",
        "인용목록": 인용, "전제목록": 전제, "해야할일": [],
        "신뢰등급": None, "버전스탬프": None, "참조사슬": [],
    }
    monkeypatch.setitem(sys.modules, "orchestrate", 가짜)
    from server import main
    monkeypatch.setattr(main._워치독, "게이트", lambda *a, **k: None)
    return main


def test_실_판정_응답에_문의초안이_실린다(스텁오케):
    """🔴 이 파일의 본체. 목이 아니라 `_실_판정` 이 만든 값인지를 본다."""
    from server.models import 판정요청

    out = 스텁오케._실_판정(판정요청(정규화=정규화, 사업명="예비창업패키지",
                                 확정비목="기계장치"))
    assert out["판정"] == "판단불가"
    assert out.get("문의초안"), "실경로 응답에 문의초안이 없다 — 엔진에 만드는 코드가 없다"
    assert "디자이너 업무용 노트북(250만원)" in out["문의초안"]
    assert not _흔적검사(out["문의초안"])


def test_실_판정이_판단불가가_아니면_키가_없다(스텁오케, monkeypatch):
    """falsy 면 키를 아예 안 싣는 계약(`main.py`)이 실경로에서도 그대로인가."""
    import orchestrate
    monkeypatch.setattr(orchestrate, "판정", lambda *a, **k: {
        "판정": "가능", "요약": "가능합니다", "인용목록": 인용, "전제목록": [],
        "해야할일": [], "신뢰등급": "B", "버전스탬프": None, "참조사슬": []})
    from server.models import 판정요청

    out = 스텁오케._실_판정(판정요청(정규화=정규화, 사업명="예비창업패키지"))
    assert out["판정"] == "가능"
    assert "문의초안" not in out


def test_오케가_준_초안을_안_덮어쓴다(스텁오케, monkeypatch):
    """엔진이 언젠가 자기 초안을 주면 그게 이긴다 — 코드 조립본이 덮으면 퇴행이다."""
    import orchestrate
    원래 = orchestrate.판정
    monkeypatch.setattr(orchestrate, "판정",
                        lambda *a, **k: {**원래(), "문의초안": "엔진이 만든 초안"})
    from server.models import 판정요청

    out = 스텁오케._실_판정(판정요청(정규화=정규화, 사업명="예비창업패키지"))
    assert out["문의초안"] == "엔진이 만든 초안"
