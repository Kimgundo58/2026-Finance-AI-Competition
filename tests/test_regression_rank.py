client = TestClient(app)


def 목록(**q):
    r = client.get("/api/plans", params=q)
    assert r.status_code == 200, r.text
    return r.json()


def 할일(**q):
    r = client.get("/api/tasks", params=q)
    assert r.status_code == 200, r.text
    return r.json()


def _내림차순(값들) -> bool:
    return all(a >= b for a, b in zip(값들, 값들[1:]))


def _오름차순(값들) -> bool:
    return all(a <= b for a, b in zip(값들, 값들[1:]))


