"""회귀 — **순위·집계 회귀**. 총계가 맞아도 순서가 틀리면 화면은 틀린다.

    PYTHONIOENCODING=utf-8 python -m pytest tests/test_regression_rank.py -q

🔴 왜 «건수» 만으로는 못 잡는가
   목록 API 는 필터·정렬·페이지네이션이 한 함수 안에서 순서대로 얽힌다
   (`routes_plans.목록` → `_거르기` → `_정렬` → 슬라이스). 여기서 나는 회귀는
   **건수가 그대로인 채 순서만 틀어지는** 모양이다 — 정렬 키를 바꿔도 건수는 5,
   페이지를 잘못 잘라도 합계는 5. 그래서 값의 «순서» 와 «페이지 합집합» 을 본다.

   같은 이유로 통계도 본다. 계약 §3-1 은 «통계는 필터 적용 전 전체 기준» 이다 —
   탭을 눌렀는데 배지 숫자가 같이 움직이면 사용자는 자기가 뭘 눌렀는지 잃는다.
   그 회귀 역시 «탭별 건수» 만 보면 안 잡힌다.

이 파일도 검증만 한다. 깨지면 해당 계통에서 고친다.
"""
