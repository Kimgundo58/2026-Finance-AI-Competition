def test_목_데이터가_4way_와_점검전을_전부_갖는다():
    판정들 = [p["판정"] for p in mock_data.목_계획]
    for v in 판정_ENUM:
        assert v in 판정들, f"목 데이터에 «{v}» 화면을 그릴 계획이 없다"
    assert None in 판정들, "목 데이터에 「점검 전」(판정 null) 행이 없다"


def test_목_할일이_체크리스트와_캘린더를_둘_다_그린다():
    assert any(t["due_date"] is None for t in mock_data.목_할일), "체크리스트 전용 행이 없다"
    assert any(t["due_date"] for t in mock_data.목_할일), "캘린더에 뜰 행이 없다"
    assert any(t["출처"] == "user" for t in mock_data.목_할일), "사용자 추가 행이 없다"
    assert any(t["날짜_사용자수정"] for t in mock_data.목_할일), "날짜 사용자수정 행이 없다"
