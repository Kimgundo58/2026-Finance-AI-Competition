# ③ 통계는 «필터 적용 전» 이다 — 탭을 눌러도 배지가 안 흔들린다
# ════════════════════════════════════════════════════════════════════

_탭들 = ("전체", "확인필요", "위험", "특이사항없음", "점검전")


@pytest.mark.parametrize("탭", _탭들)
def test_통계는_탭에_흔들리지_않는다(탭):
    기준 = 목록()["통계"]
    assert 목록(탭=탭)["통계"] == 기준, f"탭={탭} 에서 통계가 움직였다 (계약 §3-1 ⚠️)"


def test_통계는_다른_필터에도_흔들리지_않는다():
    기준 = 목록()["통계"]
    for 필터 in ({"사업명": "초기창업패키지"}, {"확정비목": "기계장치"},
                {"q": "노트북"}, {"금액_최소": 1_000_000}, {"금액_최대": 500_000}):
        assert 목록(**필터)["통계"] == 기준, f"필터 {필터} 에서 통계가 움직였다"


def test_통계_네칸의_합이_전체다():
    s = 목록()["통계"]
    assert s["확인필요"] + s["위험"] + s["특이사항없음"] + s["점검전"] == s["전체"], \
        f"통계 칸 합이 전체와 다르다 — 4-way 중 어느 하나가 어느 칸에도 안 세어졌다: {s}"


def test_금액합계는_전체_기준이다():
    s = 목록()["통계"]
    assert s["금액합계"] == float(sum(p["금액"] for p in mock_data.목_계획))
    assert 목록(탭="위험")["통계"]["금액합계"] == s["금액합계"]


