# ════════════════════════════════════════════════════════════════════
# ⑤ 할일 — 캘린더 순서 (`due_date` 오름차순 · 없는 행은 맨 뒤)
# ════════════════════════════════════════════════════════════════════

def test_할일은_due_date_오름차순이고_없는_행이_맨_뒤다():
    행 = 할일()["항목"]
    값 = [t["due_date"] or "9999-99-99" for t in 행]
    assert _오름차순(값), f"할일이 날짜순이 아니다: {값}"
    널자리 = [i for i, t in enumerate(행) if t["due_date"] is None]
    if 널자리:
        assert 널자리 == list(range(len(행) - len(널자리), len(행))), \
            "due_date 없는 행(체크리스트 전용)은 캘린더 목록의 맨 뒤여야 한다"


def test_일정만은_날짜_없는_행을_뺀다():
    """🔴 체크리스트와 캘린더는 같은 행이다 — 다른 레코드를 보는 게 아니다 (계약 §4)."""
    전부 = 할일()["항목"]
    캘린더 = 할일(일정만="true")["항목"]
    assert all(t["due_date"] for t in 캘린더)
    assert [t["task_id"] for t in 캘린더] == \
           [t["task_id"] for t in 전부 if t["due_date"]], "일정만=true 가 순서를 바꿨다"
    assert 할일(일정만="true")["건수"] == len(캘린더)


def test_이후_필터는_경계일을_포함한다():
    캘린더 = 할일(일정만="true")["항목"]
    경계 = 캘린더[0]["due_date"]
    걸린 = 할일(일정만="true", 이후=경계)["항목"]
    assert any(t["due_date"] == 경계 for t in 걸린), \
        f"이후={경계} 가 같은 날짜를 잘라냈다 — 캘린더에서 오늘 일정이 사라진다"
    assert all(t["due_date"] >= 경계 for t in 걸린)


def test_할일_필터_조합이_순서를_안_바꾼다():
    기준 = [t["task_id"] for t in 할일()["항목"]]
    for 필터 in ({"상태": "준비필요"}, {"구분": "결제전"}, {"plan_id": 1}):
        걸린 = [t["task_id"] for t in 할일(**필터)["항목"]]
        assert 걸린 == [i for i in 기준 if i in set(걸린)], f"필터 {필터} 가 순서를 흔들었다"


def test_할일_건수는_항목수와_같다():
    for 필터 in ({}, {"상태": "완료"}, {"plan_id": 999}):
        j = 할일(**필터)
        assert j["건수"] == len(j["항목"]), f"필터 {필터} 에서 건수와 항목 수가 다르다"


