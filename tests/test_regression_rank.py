def test_정렬은_필터와_무관하게_유지된다():
    """🔴 필터를 건 뒤 정렬이 풀리는 회귀 — 건수는 맞으므로 총계로는 안 보인다."""
    for 탭 in ("전체", "확인필요"):
        값 = [r["금액"] for r in 목록(탭=탭, 정렬="금액많은순", 크기=100)["항목"]]
        assert _내림차순(값), f"탭={탭} 에서 정렬이 풀렸다: {값}"


