def test_탭_매핑이_4way_를_빠짐없이_덮는다():
    덮임 = []
    for 탭 in ("확인필요", "위험", "특이사항없음"):
        덮임 += list(탭_판정[탭])
    assert set(덮임) == set(판정_ENUM), \
        f"배지 3종이 4-way 를 못 덮는다 — 어느 판정이 어느 탭에도 안 뜬다: {set(판정_ENUM) - set(덮임)}"
    assert len(덮임) == len(set(덮임)), f"한 판정이 두 탭에 중복으로 뜬다: {덮임}"


@pytest.mark.parametrize("탭", _탭들)
def test_탭별_건수가_통계와_맞는다(탭):
    j = 목록(탭=탭, 크기=100)
    if 탭 == "전체":
        assert j["건수"] == j["통계"]["전체"]
    else:
        assert j["건수"] == j["통계"][탭], f"탭={탭} 목록 건수와 배지 숫자가 어긋난다"


@pytest.mark.parametrize("탭,허용", [("확인필요", ("조건부", "판단불가")),
                                    ("위험", ("불가",)),
                                    ("특이사항없음", ("가능",))])
def test_탭이_다른_판정을_안_섞는다(탭, 허용):
    for r in 목록(탭=탭, 크기=100)["항목"]:
        assert r["판정"] in 허용, f"탭={탭} 에 {r['판정']} 이 섞였다"


def test_점검전은_판정이_null_인_행뿐이다():
    행 = 목록(탭="점검전", 크기=100)["항목"]
    assert 행, "점검전 탭이 비었다 — 목 데이터는 draft 1건을 갖고 있어야 한다"
