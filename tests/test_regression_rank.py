def test_건수는_페이지_건수가_아니라_필터_후_총건수다():
    j = 목록(크기=2)
    assert j["건수"] == len(mock_data.목_계획), f"건수가 페이지 건수로 새고 있다: {j}"
    assert len(j["항목"]) == 2
    assert j["페이지"] == 1 and j["크기"] == 2


def test_페이지를_이어붙이면_한_페이지와_같다():
    """🔴 페이지 경계에서 한 건이 빠지거나 겹치는 회귀. 각 페이지 건수만 세면 안 보인다."""
    전체 = [r["plan_id"] for r in 목록(정렬="금액많은순", 크기=100)["항목"]]
    이어붙임 = []
    for p in range(1, 5):
        이어붙임 += [r["plan_id"] for r in 목록(정렬="금액많은순", 페이지=p, 크기=2)["항목"]]
    assert 이어붙임 == 전체, f"페이지 이어붙이기가 전체와 다르다: {이어붙임} vs {전체}"
    assert len(set(이어붙임)) == len(이어붙임), "페이지 사이에 중복된 행이 있다"


def test_범위_밖_페이지는_빈_항목이지만_건수는_그대로다():
    j = 목록(페이지=99, 크기=2)
    assert j["항목"] == []
    assert j["건수"] == len(mock_data.목_계획), "빈 페이지에서 건수가 0 으로 무너졌다"


def test_페이지_0_과_크기_초과는_422():
    assert client.get("/api/plans", params={"페이지": 0}).status_code == 422
    assert client.get("/api/plans", params={"크기": 999}).status_code == 422


