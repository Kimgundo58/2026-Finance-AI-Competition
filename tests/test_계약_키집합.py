"""목 응답 키집합 == 실경로 응답 키집합.   **[계약 회귀축]**

🔴 **왜 있는가 (2026-09-03).** 어제 테스트 241건이 전부 초록인 채로 결함 셋이 살아
   있었다. 셋 다 뿌리가 하나다 — «목이 응답을 만들어 주는 자리에서 초록은
   실경로가 돈다의 증거가 아니다».

   ⓐ `_목_판정` 이 `인용` 을 직접 박아 놔서, 오케가 `인용목록` 으로 돌려주는 걸
      아무도 못 봤다. 실서버 판정 전수가 화면 7(근거) 무지로 나갔다
   ⓑ conftest autouse 픽스처가 매 테스트 MOCK 을 되돌려 RLS 격리 테스트가 목으로 흘렀다
   ⓒ 로컬 `postgres` 가 superuser+bypassrls 라 RLS 가 애초에 적용된 적이 없다

**값이 아니라 키 이름을 본다.** 실 DB·실 LLM 없이 돈다 — 오케 반환을 가짜로 물리고
실경로 조립부(`_실_판정`·`_실_상세`)를 직접 부른다. HTTP 도 안 탄다.

🔴 **가짜 오케 반환의 키 이름을 여기 손으로 적지 않는다.** `llm_schema.최종응답`
   에서 뽑아 쓴다 — 손으로 적으면 스키마가 바뀌어도 이 테스트가 같이 안 바뀌어
   «목이 가린다» 를 이 파일이 다시 저지른다.

이 파일은 모드와 무관하다 (conftest 의 `MOCK` 스위치를 안 탄다).
"""
