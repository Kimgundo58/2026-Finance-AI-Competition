# ① /api/judge — 오케 → 실경로 키 이름 다리
# ════════════════════════════════════════════════════════════════════

def test_실경로가_오케_키이름을_전부_읽는다(오케물리기):
    """🔴 어제 결함 ⓐ 를 잡는 축이다.

    오케는 스키마 이름(`인용목록`·`전제목록`)으로 돌려주고 실경로는 계약 이름
    (`인용`·`전제`)으로 내보낸다. 이름이 어긋나면 폴백이 먹어 **키는 있는데 값이 빈다** —
    목은 값을 직접 박아 놔서 이걸 영원히 못 본다.
    """
    out = _실판정_돌리기()
    빈칸 = [k for k in 계약키 if not out.get(k)]
    assert not 빈칸, (
        f"오케가 채워 보냈는데 실경로가 못 읽은 키: {빈칸}. "
        f"오케 스키마 이름 {[f.name for f in _필드(llm_schema.최종응답)]} 과 "
        f"대조하라 — 이름이 다른 키는 폴백을 달아야 한다")


def test_목과_실경로_판정_키집합이_같다(오케물리기):
    out = _실판정_돌리기()
    실키 = set(out) - _실경로_추가허용
    assert 실키 == 계약키, (
        f"목에만 있음(실서버에서 빈다): {sorted(계약키 - 실키)} · "
        f"실경로에만 있음(프론트가 모르는 키): {sorted(실키 - 계약키)}")


def test_목_4way_키집합이_서로_같다():
    """프론트는 `?목=` 으로 네 화면을 만든다 — 갈래마다 키가 다르면 화면이 갈린다.

    `문의초안` 만 예외다 — 판단불가에만 붙는 게 설계고 실경로도 조건부로만 싣는다.
    """
    갈래 = {이름: set(값) - _실경로_추가허용 for 이름, 값 in 서버._목_판정.items()}
    기준 = 갈래["가능"]
    다른것 = {이름: sorted(기준 ^ 키) for 이름, 키 in 갈래.items() if 키 != 기준}
    assert not 다른것, f"4-way 갈래마다 키가 다르다: {다른것}"


