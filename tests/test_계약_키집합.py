# 계약 — 프론트가 읽는 판정 키. 목이 약속한 것이 기준이다
# ════════════════════════════════════════════════════════════════════

# 🔴 «목이 내보내는 키» 를 계약으로 삼는다. 프론트가 목에 붙어 화면을 만들었으므로
#    목에 있는데 실경로에 없는 키는 그 자리가 실서버에서 빈다.
계약키 = set(서버._목_판정["가능"])

# 실경로에만 있는 내부 키 — 프론트로 안 나간다 (`gen()` 이 벗겨내거나 조건부로만 싣는다)
_실경로_추가허용 = {"decision_id", "문의초안"}


def _가짜_오케반환() -> dict:
    """`llm_schema.최종응답` 의 **필드 이름 그대로** 채운 오케 반환.

    값은 전부 「비지 않은」 센티널이다 — 실경로가 키 이름을 잘못 읽으면 폴백
    기본값(`[]`·`None`)이 나오므로 **빈 값 = 키 이름을 못 읽었다** 가 된다.
    """
    인용 = llm_schema.인용(s번호="S14", doc_id="D1", 조번호="제39조", 조제목="기계장치",
                          원문="…", extraction="text")
    전제 = llm_schema.전제(사실="협약상 참여인력이다", 근거조항="S14",
                          매핑=["F4.역할"], 미충족시="불가")
    r = llm_schema.최종응답(
        판정="조건부",
        요약="사전승인을 받으면 구매할 수 있습니다.",
        해야할일=[{"항목": "사전승인 신청", "설명": "100만원 이상은 사전승인이 필요합니다."}],
        인용목록=[인용],
        전제목록=[전제],
        신뢰등급="B",
        버전스탬프="제14차, 2025.12.23 기준",
        참조사슬=[{"표기": "지침 제39조", "관계": "준용"}],
    )
    반환 = r.to_dict()
    # 조립기가 실제로 얹는 키. 스키마 밖이라 dataclass 에 없다
    반환["decision_id"] = 4242
    return 반환


@pytest.fixture
def 오케물리기(monkeypatch):
    """`_실_판정` 안의 `import orchestrate` 가 가짜를 집게 한다. 실 LLM·실 DB 없음."""
    가짜 = types.ModuleType("orchestrate")
    호출 = {}

    def 판정(질문, **kw):
        호출["질문"] = 질문
        호출.update(kw)
        return _가짜_오케반환()

    가짜.판정 = 판정
    monkeypatch.setitem(sys.modules, "orchestrate", 가짜)
    monkeypatch.setattr(서버._워치독, "게이트", lambda: None)
    return 호출


def _실판정_돌리기() -> dict:
    return 서버._실_판정(판정요청(
        정규화={"_원문": "디자이너가 쓸 맥북 프로 250만원", "비목후보": []},
        사업명="예비창업패키지",
    ))


